// Normalize authored sprite sheets to the existing 640px canvas / y=600 floor.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { PAINTED_OUTFITS } from '../src/content/paintedOutfits.js';
const require = createRequire(import.meta.url);
let sharp; try { sharp = require('sharp'); } catch { sharp = require('../work/deps/node_modules/sharp'); }
const groups = {
  rogue: ['prepared', ['rogue','rogue-duelist','rogue-nightveil','rogue-shadow']],
  starseer: ['starstoneCharge', ['starseer','starseer-astral','starseer-eclipse','starseer-starlit']],
  herald: ['bloodRite', ['herald','herald-emberhabit','herald-ossuary','herald-pilgrim']],
};
const frames = {};
for (const [group,[pose, ids]] of Object.entries(groups)) {
  for (const transition of [false,true]) {
  const framePose = transition ? `${pose}Transition` : pose;
  const {data,info} = await sharp(`art/readiness-poses/sources/${group}${transition?'-transition':''}.png`).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  const cell = Math.floor(info.width / 2);
  for (const [index,id] of ids.entries()) {
    const pixels = Buffer.alloc(cell*cell*4);
    let x0=cell,y0=cell,x1=0,y1=0;
    for(let y=0;y<cell;y++) for(let x=0;x<cell;x++) {
      const at=((y+Math.floor(index/2)*cell)*info.width+x+(index%2)*cell)*4, out=(y*cell+x)*4;
      const [r,g,b] = data.subarray(at,at+3);
      // Chroma-key only high-chroma magenta; keep dark purple outfit material.
      const matte = Math.min(r,b)>110 && Math.min(r,b)-g>65;
      const a = matte ? 0 : data[at+3];
      pixels[out]=r; pixels[out+1]=g; pixels[out+2]=b; pixels[out+3]=a;
      if(a>20){x0=Math.min(x0,x);x1=Math.max(x1,x);y0=Math.min(y0,y);y1=Math.max(y1,y);}
    }
    // Unmix magenta only along the extracted boundary, preserving purple cloth
    // inside the silhouette. This removes the colored one-pixel source fringe.
    const original=Buffer.from(pixels);
    for(let y=2;y<cell-2;y++) for(let x=2;x<cell-2;x++) {
      const at=(y*cell+x)*4;
      if(!original[at+3]) continue;
      let edge=false;
      for(let dy=-2;dy<=2;dy++) for(let dx=-2;dx<=2;dx++) if(!original[((y+dy)*cell+x+dx)*4+3]) edge=true;
      if(!edge) continue;
      const r=original[at],g=original[at+1],b=original[at+2], spill=Math.max(0,Math.min(r,b)-g);
      if(spill<20) continue;
      const alpha=1-spill/255;
      pixels[at]=Math.max(0,(r-255*(1-alpha))/alpha);
      pixels[at+1]=Math.min(255,g/alpha);
      pixels[at+2]=Math.max(0,(b-255*(1-alpha))/alpha);
      pixels[at+3]=Math.round(alpha*255);
    }
    // Staff is raised above the head; reserve 16% extra height for it rather
    // than shrinking the body to the idle staff's bounding box.
    const reference = PAINTED_OUTFITS[id].frames.idle.box;
    const height = Math.round((601-reference.y0)*(group==='starseer'&&!transition?1.16:1));
    const width = Math.round((x1-x0+1)*height/(y1-y0+1));
    const left=Math.round(320-width/2), top=601-height;
    if(left<0||top<0||left+width>640) throw Error(`${id} clips`);
    const cut=await sharp(pixels,{raw:{width:cell,height:cell,channels:4}}).extract({left:x0,top:y0,width:x1-x0+1,height:y1-y0+1}).resize(width,height).png().toBuffer();
    const file=`assets/readiness-poses/${id}/${framePose}.webp`;
    mkdirSync(`assets/readiness-poses/${id}`,{recursive:true});
    await sharp({create:{width:640,height:640,channels:4,background:'#00000000'}}).composite([{input:cut,left,top}]).webp({quality:90,alphaQuality:100}).toFile(file);
    frames[id]={...frames[id],[framePose]:{file,box:{x0:left,y0:top,x1:left+width-1,y1:600}}};
  }
}
}
writeFileSync('src/content/readinessPoseArt.js','// Generated by tools/readiness-poses-ship.mjs.\nexport const READINESS_POSE_ART = '+JSON.stringify(frames,null,2)+';\n');
console.log('Shipped 12 readiness poses and 12 transition frames.');
