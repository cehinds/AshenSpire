#!/usr/bin/env node
// tools/enemy-sheets.mjs - one editable character sheet per Core enemy (owner request 2026-11-01).
//
// The sheets in games/ashenspire/packs/core/enemies/<enemyId>.json are the source of truth for the enemy
// rows of characters.json. Each sheet holds the enemy's name, stats, equipment, current deck, reserve deck,
// AI hints and behaviour, written with typed reference tags (card:..., gear:..., relic:...).
// _reference.json / _reference.md (generated) say what every id maps to.
//
//   node tools/enemy-sheets.mjs --extract [--force]   create the sheets once from today's characters.json
//   node tools/enemy-sheets.mjs --write               sheets -> characters.json rows, derived blocks, reference table
//   node tools/enemy-sheets.mjs --check               exit 1 if the sheets, characters.json or the reference disagree,
//                                                     or any reference tag does not resolve
//   (add --pack <dir> to act on another pack directory; tests do)
//
// Schema and reference prefixes: DEVELOPER.md, "Editing enemies".
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const DEFAULT_PACK = join(ROOT, 'games/ashenspire/packs/core');
export const PREFIXES = ['card', 'gear', 'relic', 'enemy'];
const ENEMY_TAG = 'character.enemy';
const ROW_ORDER = ['id', 'name', 'tags', 'attributes', 'attributePriority', 'spFloor', 'levelProfile', 'defaultDeck', 'defaultGear', 'defaultRelics', 'presentation', 'enemy'];
const ENEMY_ORDER = ['unlockCards', 'firstCard', 'poiseMax', 'arcaneExposure', 'blighted', 'phases', 'cardHints', 'startingRange', 'rangeClosingMove', 'rangeRoutePolicy', 'rangeRetreatMove', 'weaknesses'];
const GENERATED = 'generated by tools/enemy-sheets.mjs --write, edits are ignored';
const json = path => JSON.parse(readFileSync(path, 'utf8'));
const text = value => `${JSON.stringify(value, null, 2)}\n`;
const sameJson = (a, b) => JSON.stringify(a) === JSON.stringify(b);
const display = name => String(name).replace(/_/g, ' ');
const rowName = name => String(name).replace(/ /g, '_');
export const ref = (type, id) => `${type}:${id}`;

export function loadPack(pack = DEFAULT_PACK) {
  return {
    pack,
    rows: json(join(pack, 'characters.json')),
    cards: json(join(pack, 'enemyCards.json')),
    gear: json(join(pack, 'gear.json')),
    relics: json(join(pack, 'enemyRelics.json')),
  };
}

// ---- extract: characters.json enemy row -> sheet ----
const mapPhases = (phases, fn) => phases.map(p => (Array.isArray(p.unlockCards) ? { ...p, unlockCards: p.unlockCards.map(fn) } : p));

export function sheetFromRow(row) {
  const e = row.enemy || {};
  if (rowName(display(row.name)) !== row.name) throw new Error(`${row.id}: name "${row.name}" is not reversible (contains a space)`);
  const card = id => ref('card', id);
  const { poiseMax, cardHints = {}, unlockCards, firstCard, phases, ...restEnemy } = e;
  const behaviour = {};
  if (firstCard !== undefined) behaviour.firstCard = card(firstCard);
  if (phases !== undefined) behaviour.phases = mapPhases(phases, card);
  Object.assign(behaviour, restEnemy, { presentation: row.presentation });
  const stats = {};
  if (row.attributes !== undefined) stats.attributes = row.attributes;
  stats.attributePriority = row.attributePriority;
  stats.levelProfile = row.levelProfile;
  stats.poiseMax = poiseMax;
  if (row.spFloor !== undefined) stats.spFloor = row.spFloor;
  const sheet = {
    id: row.id,
    name: display(row.name),
    tags: row.tags,
    stats,
    derived: null,
    equipment: row.defaultGear.map(g => ({ slot: g.key, ref: ref('gear', g.id) })),
    relics: row.defaultRelics.map(g => ({ slot: g.key, ref: ref('relic', g.id) })),
    deck: row.defaultDeck.map(card),
    reserve: (unlockCards || []).map(card),
    ai: Object.fromEntries(Object.entries(cardHints).map(([id, hint]) => [card(id), hint])),
    behaviour,
    keyOrder: { row: Object.keys(row), enemy: Object.keys(e) },
  };
  sheet.derived = deriveFor(sheet);
  return sheet;
}

export function deriveFor(sheet) {
  const tier = (sheet.tags.find(t => t.startsWith('tier.')) || '').slice(5) || null;
  return {
    _note: `${GENERATED}. Everything above this block is the part to edit.`,
    tier,
    deckSize: sheet.deck.length,
    reserveSize: sheet.reserve.length,
    distinctCards: new Set(sheet.deck).size,
    levelRange: `${sheet.stats.levelProfile?.min}-${sheet.stats.levelProfile?.max}`,
  };
}

// ---- validate refs ----
function split(tag) {
  const i = typeof tag === 'string' ? tag.indexOf(':') : -1;
  return i < 0 ? [null, tag] : [tag.slice(0, i), tag.slice(i + 1)];
}

export function catalogOf(pack) {
  return { card: new Set(pack.cards.map(c => c.id)), gear: new Set(pack.gear.map(g => g.id)), relic: new Set(pack.relics.map(r => r.id)),
    enemy: new Set(pack.rows.filter(r => r.tags.includes(ENEMY_TAG)).map(r => r.id)) };
}

function suggest(set, id) {
  const stem = String(id).split('.')[0];
  const near = [...set].filter(x => x.startsWith(`${stem}.`) || x.startsWith(String(id).slice(0, 4)));
  return near.length ? ` Known near it: ${near.slice(0, 6).join(', ')}.` : '';
}

// Returns a list of problem strings (empty when clean). `where` is e.g. "wanderingSoldier.json deck[2]".
export function checkRef(tag, want, where, catalog) {
  const [type, id] = split(tag);
  if (type === null) return [`${where}: "${tag}" has no reference prefix; write ${want}:<id>`];
  if (type !== want) return [`${where}: "${tag}" is a ${type}: reference but this slot takes ${want}: references`];
  if (!catalog[type].has(id)) return [`${where}: unknown ${want} id "${id}" (from "${tag}").${suggest(catalog[type], id)}`];
  return [];
}

const SHEET_KEYS = ['id', 'name', 'tags', 'stats', 'derived', 'equipment', 'relics', 'deck', 'reserve', 'ai', 'behaviour', 'keyOrder'];
const STATS_KEYS = ['attributes', 'attributePriority', 'levelProfile', 'poiseMax', 'spFloor'];
const SLOT_KEYS = ['slot', 'ref'];
const unknownKeys = (obj, allowed, where, hint) => (obj && typeof obj === 'object' && !Array.isArray(obj) ? Object.keys(obj).filter(k => !allowed.includes(k))
  .map(k => `${where}: unknown key "${k}". Allowed keys: ${allowed.join(', ')}.${hint || ''}`) : []);

export function validateSheet(sheet, file, catalog) {
  const problems = [];
  const at = path => `${file} ${path}`;
  problems.push(...unknownKeys(sheet, SHEET_KEYS, file, ' Extra enemy fields go under "behaviour".'));
  problems.push(...unknownKeys(sheet.stats, STATS_KEYS, `${file} stats`, ' Extra enemy fields go under "behaviour".'));
  for (const list of ['equipment', 'relics']) (sheet[list] || []).forEach((g, i) => problems.push(...unknownKeys(g, SLOT_KEYS, `${file} ${list}[${i}]`)));
  for (const k of ['id', 'name', 'tags', 'stats', 'equipment', 'relics', 'deck', 'reserve', 'ai', 'behaviour']) if (sheet[k] === undefined) problems.push(`${file}: missing field "${k}"`);
  if (problems.length) return problems;
  if (`${sheet.id}.json` !== file) problems.push(`${file}: id "${sheet.id}" must match the file name`);
  if (!sheet.tags.includes(ENEMY_TAG)) problems.push(`${file}: tags must include ${ENEMY_TAG}`);
  if (String(sheet.name).includes('_')) problems.push(`${file}: name uses spaces, not underscores`);
  sheet.equipment.forEach((g, i) => problems.push(...checkRef(g.ref, 'gear', at(`equipment[${i}]`), catalog)));
  sheet.relics.forEach((g, i) => problems.push(...checkRef(g.ref, 'relic', at(`relics[${i}]`), catalog)));
  sheet.deck.forEach((c, i) => problems.push(...checkRef(c, 'card', at(`deck[${i}]`), catalog)));
  sheet.reserve.forEach((c, i) => problems.push(...checkRef(c, 'card', at(`reserve[${i}]`), catalog)));
  for (const c of Object.keys(sheet.ai)) {
    problems.push(...checkRef(c, 'card', at(`ai key`), catalog));
    if (!sheet.deck.includes(c) && !sheet.reserve.includes(c)) problems.push(`${file}: ai hint "${c}" is for a card in neither deck nor reserve`);
  }
  if (sheet.behaviour.firstCard !== undefined) problems.push(...checkRef(sheet.behaviour.firstCard, 'card', at('behaviour.firstCard'), catalog));
  (sheet.behaviour.phases || []).forEach((p, i) => (p.unlockCards || []).forEach((c, j) => problems.push(...checkRef(c, 'card', at(`behaviour.phases[${i}].unlockCards[${j}]`), catalog))));
  const unlocked = new Set((sheet.behaviour.phases || []).flatMap(p => p.unlockCards || []));
  for (const c of sheet.reserve) if (!unlocked.has(c)) problems.push(`${file}: reserve card "${c}" is not listed in any behaviour.phases[].unlockCards, so it would never enter play`);
  for (const c of unlocked) if (!sheet.reserve.includes(c)) problems.push(`${file}: phase unlocks "${c}" but it is not in reserve; add it to reserve`);
  return problems;
}

// ---- build: sheet -> characters.json row ----
const bare = tag => split(tag)[1];
const inOrder = (obj, order) => {
  const keys = [...(order || []).filter(k => k in obj), ...Object.keys(obj).filter(k => !(order || []).includes(k))];
  return Object.fromEntries(keys.map(k => [k, obj[k]]));
};

export function rowFromSheet(sheet) {
  const { firstCard, phases, presentation, ...restBehaviour } = sheet.behaviour;
  const enemy = { poiseMax: sheet.stats.poiseMax, cardHints: Object.fromEntries(Object.entries(sheet.ai).map(([c, h]) => [bare(c), h])), ...restBehaviour };
  if (sheet.reserve.length) enemy.unlockCards = sheet.reserve.map(bare);
  if (firstCard !== undefined) enemy.firstCard = bare(firstCard);
  if (phases !== undefined) enemy.phases = mapPhases(phases, bare);
  const { attributes, attributePriority, levelProfile, spFloor } = sheet.stats;
  const row = { id: sheet.id, name: rowName(sheet.name), tags: sheet.tags, attributePriority, levelProfile,
    defaultDeck: sheet.deck.map(bare),
    defaultGear: sheet.equipment.map(g => ({ key: g.slot, id: bare(g.ref) })),
    defaultRelics: sheet.relics.map(g => ({ key: g.slot, id: bare(g.ref) })),
    presentation, enemy: inOrder(enemy, sheet.keyOrder?.enemy || ENEMY_ORDER) };
  if (attributes !== undefined) row.attributes = attributes;
  if (spFloor !== undefined) row.spFloor = spFloor;
  return inOrder(row, sheet.keyOrder?.row || ROW_ORDER);
}

// ---- sheets on disk ----
export const sheetsDir = pack => join(pack, 'enemies');
export function loadSheets(pack) {
  const dir = sheetsDir(pack);
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter(f => f.endsWith('.json') && !f.startsWith('_')).sort().map(file => {
    try { return { file, sheet: json(join(dir, file)) }; } catch (e) { throw new Error(`enemies/${file}: ${e.message}`); }
  });
}

// Merge built rows into the existing array: non-enemy rows and order untouched, new enemies appended by id.
export function mergeRows(rows, sheets) {
  const built = new Map(sheets.map(({ sheet }) => [sheet.id, rowFromSheet(sheet)]));
  const out = [];
  for (const r of rows) {
    if (!r.tags.includes(ENEMY_TAG)) out.push(r);
    else if (built.has(r.id)) { out.push(built.get(r.id)); built.delete(r.id); }
  }
  for (const id of [...built.keys()].sort()) out.push(built.get(id));
  return out;
}

// ---- reference table ----
const short = s => String(s ?? '').replace(/\s+/g, ' ').trim();
export function buildReference(pack, sheets) {
  const used = { card: new Set(), gear: new Set(), relic: new Set() };
  for (const { sheet } of sheets) {
    [...sheet.deck, ...sheet.reserve, ...Object.keys(sheet.ai)].forEach(t => used.card.add(bare(t)));
    sheet.equipment.forEach(g => used.gear.add(bare(g.ref)));
    sheet.relics.forEach(g => used.relic.add(bare(g.ref)));
  }
  const cards = {}, gear = {}, relics = {}, enemies = {};
  for (const c of pack.cards) cards[ref('card', c.id)] = { name: display(c.name), type: c.type, cost: { stamina: c.staminaCost ?? c.cost, mana: c.manaCost ?? 0 }, text: short(c.textTemplate), usedBy: [...used.card].includes(c.id) ? 'enemy sheet' : 'unused' };
  for (const g of pack.gear) gear[ref('gear', g.id)] = { name: display(g.name), slot: g.slot, kind: g.kind, rarity: g.rarity, tags: g.tags, ...(g.range ? { range: g.range } : {}), ...(g.points && Object.keys(g.points).length ? { points: g.points } : {}) };
  for (const r of pack.relics) relics[ref('relic', r.id)] = { name: display(r.name), text: short(r.text), modifiers: r.modifiers };
  for (const { sheet } of sheets) enemies[ref('enemy', sheet.id)] = { name: sheet.name, tier: sheet.derived?.tier ?? deriveFor(sheet).tier };
  for (const t of ['card', 'gear', 'relic']) for (const id of used[t]) if (!{ card: cards, gear, relic: relics }[t][ref(t, id)]) throw new Error(`reference: ${t}:${id} missing`);
  return { _generated: `${GENERATED}. Edit games/ashenspire/packs/core/enemies/<id>.json instead.`, enemies, cards, gear, relics };
}

export function referenceMarkdown(refTable) {
  const esc = s => String(s).replace(/\|/g, '\\|');
  const table = (title, head, rows) => [`## ${title}`, '', `| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map(r => `| ${r.map(esc).join(' | ')} |`), ''];
  return [
    '<!-- GENERATED by tools/enemy-sheets.mjs --write. Do not edit. -->', '', '# Enemy sheet reference', '',
    'What every reference tag in `enemies/<id>.json` means. Generated, do not edit.', '',
    ...table('Enemies (enemy:)', ['ref', 'name', 'tier'], Object.entries(refTable.enemies).map(([k, v]) => [k, v.name, v.tier])),
    ...table('Cards (card:)', ['ref', 'name', 'type', 'SP', 'MP', 'text'], Object.entries(refTable.cards).map(([k, v]) => [k, v.name, v.type, v.cost.stamina, v.cost.mana, v.text])),
    ...table('Gear (gear:)', ['ref', 'name', 'slot', 'kind', 'rarity', 'tags'], Object.entries(refTable.gear).map(([k, v]) => [k, v.name, v.slot, v.kind, v.rarity, (v.tags || []).join(', ')])),
    ...table('Relics (relic:)', ['ref', 'name', 'text'], Object.entries(refTable.relics).map(([k, v]) => [k, v.name, v.text])),
  ].join('\n');
}

// ---- operations ----
export function extract(pack = DEFAULT_PACK, { force = false } = {}) {
  const data = loadPack(pack);
  const dir = sheetsDir(pack);
  mkdirSync(dir, { recursive: true });
  const written = [];
  for (const row of data.rows.filter(r => r.tags.includes(ENEMY_TAG))) {
    const file = join(dir, `${row.id}.json`);
    if (existsSync(file) && !force) throw new Error(`${row.id}.json exists; --extract --force overwrites sheets`);
    writeFileSync(file, text(sheetFromRow(row)));
    written.push(row.id);
  }
  return written;
}

// Returns { problems, rows, sheets, reference } without touching disk.
export function plan(pack = DEFAULT_PACK) {
  const data = loadPack(pack);
  const catalog = catalogOf(data);
  const sheets = loadSheets(pack);
  const problems = [];
  const seen = new Map();
  for (const { file, sheet } of sheets) {
    if (seen.has(sheet.id)) problems.push(`${file}: duplicate enemy id "${sheet.id}" (also ${seen.get(sheet.id)})`);
    seen.set(sheet.id, file);
    catalog.enemy.add(sheet.id);
  }
  for (const { file, sheet } of sheets) problems.push(...validateSheet(sheet, file, catalog));
  if (problems.length) return { problems, rows: data.rows, sheets, data };
  for (const s of sheets) s.sheet.derived = deriveFor(s.sheet);
  const rows = mergeRows(data.rows, sheets);
  const reference = buildReference({ ...data, rows }, sheets);
  return { problems, rows, sheets, data, reference, md: referenceMarkdown(reference) };
}

export function write(pack = DEFAULT_PACK) {
  const p = plan(pack);
  if (p.problems.length) return p;
  writeFileSync(join(pack, 'characters.json'), text(p.rows));
  for (const { file, sheet } of p.sheets) writeFileSync(join(sheetsDir(pack), file), text(sheet));
  writeFileSync(join(sheetsDir(pack), '_reference.json'), text(p.reference));
  writeFileSync(join(sheetsDir(pack), '_reference.md'), p.md);
  return p;
}

export function check(pack = DEFAULT_PACK) {
  const p = plan(pack);
  if (p.problems.length) return p.problems;
  const problems = [];
  const dir = sheetsDir(pack);
  const onDisk = new Map(p.data.rows.map(r => [r.id, r]));
  const built = new Map(p.rows.map(r => [r.id, r]));
  const sheetIds = new Set(p.sheets.map(s => s.sheet.id));
  for (const id of onDisk.keys()) if (onDisk.get(id).tags.includes(ENEMY_TAG) && !sheetIds.has(id)) problems.push(`enemies/${id}.json is missing; restore it, or run --write to REMOVE enemy ${id} from characters.json`);
  for (const id of new Set([...onDisk.keys(), ...built.keys()])) {
    if (onDisk.has(id) && built.has(id) && !sameJson(onDisk.get(id), built.get(id))) problems.push(`characters.json row "${id}" disagrees with enemies/${id}.json (if another tool rewrote the rows, run --extract --force to rebuild the sheets from them)`);
    else if (!onDisk.has(id)) problems.push(`enemies/${id}.json is a new enemy not in characters.json; run --write`);
  }
  if (!problems.length && text(p.rows) !== readFileSync(join(pack, 'characters.json'), 'utf8')) problems.push('characters.json differs from the sheets in key order or formatting');
  for (const { file, sheet } of p.sheets) {
    if (text(sheet) !== readFileSync(join(dir, file), 'utf8')) problems.push(`enemies/${file}: derived block or formatting is stale`);
  }
  const rj = join(dir, '_reference.json'), rm = join(dir, '_reference.md');
  if (!existsSync(rj) || readFileSync(rj, 'utf8') !== text(p.reference)) problems.push('enemies/_reference.json is stale');
  if (!existsSync(rm) || readFileSync(rm, 'utf8') !== p.md) problems.push('enemies/_reference.md is stale');
  if (problems.length) problems.push('fix: node tools/enemy-sheets.mjs --write');
  return problems;
}

// ---- CLI ----
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const at = args.indexOf('--pack');
  const pack = at >= 0 ? resolve(args[at + 1]) : DEFAULT_PACK;
  try {
    if (args.includes('--extract')) console.log(`enemy-sheets: extracted ${extract(pack, { force: args.includes('--force') }).length} sheets`);
    else if (args.includes('--write')) {
      const p = write(pack);
      if (p.problems.length) { console.error(p.problems.join('\n')); process.exit(1); }
      console.log(`enemy-sheets: wrote ${p.sheets.length} sheets into characters.json and the reference table`);
    } else if (args.includes('--check')) {
      const problems = check(pack);
      if (problems.length) { console.error(`enemy-sheets: ${problems.length} problem(s)\n${problems.join('\n')}`); process.exit(1); }
      console.log('enemy-sheets: ok');
    } else { console.error('usage: enemy-sheets.mjs --extract [--force] | --write | --check [--pack <dir>]'); process.exit(2); }
  } catch (e) { console.error(`enemy-sheets: ${e.message}`); process.exit(1); }
}
