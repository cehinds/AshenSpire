#!/usr/bin/env node
// tools/hud-layout-css.mjs — compile content/hud-layout/<form-factor>.json into
// styles/hud-layout.generated.css (contract: docs/hud-layout-tokens.md).
//
//   node tools/hud-layout-css.mjs            validate and write (same as --write)
//   node tools/hud-layout-css.mjs --write    validate and write
//   node tools/hud-layout-css.mjs --check    validate; exit 1 when the file on
//                                            disk differs from the output
//
// Every error names the file and the token and exits 1. tests/run-node.mjs
// runs --check; tools/launch.mjs runs --write before bundling.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { FORM_FACTORS, HUD_LAYOUT_TOKENS, validateHudLayoutFile } from './hud-layout-tokens.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const HUD_LAYOUT_DIR = 'content/hud-layout';
export const HUD_LAYOUT_CSS = 'styles/hud-layout.generated.css';

const HEADER = '/* GENERATED by tools/hud-layout-css.mjs from content/hud-layout/*.json — do not edit */';

function block(selector, entries) {
  if (!entries.length) return `${selector} { }`;
  return `${selector} {\n${entries.map(([name, value]) => `  ${name}: ${value};`).join('\n')}\n}`;
}

/**
 * Builds the stylesheet from parsed documents keyed by form factor
 * ({ mobile: doc, ... }). Returns { css, errors }; errors name file and token.
 */
export function generateHudLayoutCss(docs, { dir = HUD_LAYOUT_DIR } = {}) {
  const errors = [];
  const overrides = {};
  for (const formFactor of FORM_FACTORS) {
    const file = `${dir}/${formFactor}.json`;
    const doc = docs[formFactor];
    if (doc === undefined) { errors.push(`${file}: missing (all four form factors are always present)`); continue; }
    for (const error of validateHudLayoutFile(doc, formFactor)) errors.push(`${file}: ${error}`);
    // Overrides are written in allowlist order, so key order in the JSON never
    // changes the output.
    const tokens = doc && typeof doc.tokens === 'object' && doc.tokens ? doc.tokens : {};
    overrides[formFactor] = HUD_LAYOUT_TOKENS.filter((token) => Object.hasOwn(tokens, token.name))
      .map((token) => [token.name, String(tokens[token.name]).trim()]);
  }
  if (errors.length) return { css: null, errors };
  const css = [
    HEADER,
    block(':root', HUD_LAYOUT_TOKENS.map((token) => [token.name, token.default])),
    ...FORM_FACTORS.map((formFactor) => block(`:root[data-form-factor='${formFactor}']`, overrides[formFactor])),
  ].join('\n') + '\n';
  return { css, errors };
}

/** Reads the four files from disk. A file that does not parse is an error. */
export function readHudLayoutDocs(root = ROOT) {
  const docs = {}, errors = [];
  for (const formFactor of FORM_FACTORS) {
    const file = `${HUD_LAYOUT_DIR}/${formFactor}.json`;
    const path = resolve(root, file);
    if (!existsSync(path)) continue;
    try { docs[formFactor] = JSON.parse(readFileSync(path, 'utf8')); }
    catch (error) { errors.push(`${file}: not valid JSON — ${error.message}`); }
  }
  return { docs, errors };
}

export function buildHudLayoutCss(root = ROOT) {
  const read = readHudLayoutDocs(root);
  if (read.errors.length) return { css: null, errors: read.errors };
  return generateHudLayoutCss(read.docs);
}

function main(argv) {
  const check = argv.includes('--check');
  const unknown = argv.filter((arg) => !['--check', '--write'].includes(arg));
  if (unknown.length) { console.error(`hud-layout-css: unknown argument(s) ${unknown.join(' ')}`); return 2; }
  const { css, errors } = buildHudLayoutCss(ROOT);
  if (errors.length) {
    console.error(`hud-layout-css: REFUSED — ${errors.length} problem(s):\n  ${errors.join('\n  ')}`);
    return 1;
  }
  const out = resolve(ROOT, HUD_LAYOUT_CSS);
  const current = existsSync(out) ? readFileSync(out, 'utf8') : null;
  if (check) {
    if (current !== css) {
      console.error(`STALE: ${HUD_LAYOUT_CSS} does not match ${HUD_LAYOUT_DIR}/ — run node tools/hud-layout-css.mjs --write`);
      return 1;
    }
    console.log(`hud-layout-css: ${HUD_LAYOUT_CSS} is current with ${FORM_FACTORS.length} form factor file(s)`);
    return 0;
  }
  if (current !== css) writeFileSync(out, css);
  console.log(`hud-layout-css: ${current === css ? 'unchanged' : 'wrote'} ${HUD_LAYOUT_CSS}`);
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) process.exit(main(process.argv.slice(2)));
