#!/usr/bin/env node
// tools/tokens-css.mjs — publish the design tokens in content/config/ui/tokens.json
// (type, layer, motion, touch) as CSS custom properties in
// styles/tokens.generated.css.
//
//   node tools/tokens-css.mjs            validate and write (same as --write)
//   node tools/tokens-css.mjs --write    validate and write
//   node tools/tokens-css.mjs --check    validate; exit 1 when the file on disk
//                                        differs from the output
//
// One home per fact: a token whose custom property styles/base.css already
// declares (--t-1, --t-2, --t-4, --tap-floor, --iconbtn-size) is marked
// `home` in tokens.json and is NOT declared again here; this tool reads the
// home stylesheet and refuses a `home` that does not declare the property, and
// a published name that some stylesheet already declares. Every error names the
// file and the token and exits 1. tests/run-node.mjs runs --check;
// tools/launch.mjs runs --write before bundling; tools/serve.mjs --watch runs
// it after config-build when tokens.json changes.
//
// Colours: color.palette (+ color.notes) becomes a `/* colours */` section of the
// :root block, and each color.themes.<k> becomes its own rule under its selector
// (body.hi-contrast, body.cb-safe), written after :root so it overrides the palette.
// camelCase keys are kebab-cased (bgRaise → --bg-raise). The tool refuses a colour
// whose name a stylesheet still declares at that selector; a scoped redeclaration
// (a component's own --gold) is the cascade and is fine.
//
// Naming: type.scale.<k> → --t-<kebab k> in rem (the root is 10px at Text M, so
// 16px is 1.6rem); layer.<k> → --layer-<kebab k>; motion.<k> → --motion-<kebab k>
// in ms; touch.<kFooPx> → --touch-<kebab foo> in px (a finger does not grow with
// Text size). An entry's `css` overrides the derived name.

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { tokenGroupProblems } from './config-build.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const TOKENS_JSON = 'content/config/ui/tokens.json';
export const TOKENS_CSS = 'styles/tokens.generated.css';
/** html { font-size: 62.5% } in styles/base.css: 1rem is 10px at Text M. */
export const REM_PX = 10;

const HEADER = '/* GENERATED by tools/tokens-css.mjs from content/config/ui/tokens.json — do not edit */';

const kebab = (key) => key.replace(/([A-Z])/g, '-$1').toLowerCase();
const num = (n) => String(+n.toFixed(4));

/** Every declared custom property name in a stylesheet's text (comments removed). */
/** A stylesheet's rule blocks as { selectors (last compound of each), body } (comments stripped; nested blocks are not parsed). */
function ruleBlocks(css) {
  const bare = css.replace(/\/\*[\s\S]*?\*\//g, '');
  return [...bare.matchAll(/([^{}]+)\{([^{}]*)\}/g)].map((m) => ({
    selectors: m[1].split(',').map((sel) => sel.trim().split(/\s+/).pop()),
    body: m[2],
  }));
}
const isRootRule = (block) => block.selectors.some((sel) => /^(:root|html)(?![\w-])/.test(sel));
const propPattern = (name, flags = '') => new RegExp(`(?:^|[{;\\s])${name.replace(/[-]/g, '\\-')}\\s*:\\s*([^;}]+)`, flags);

/**
 * The value one custom property is declared with at the root — in a rule whose
 * selector list names :root or html — or null. A scoped re-declaration earlier
 * in the file (`.component { --t-1: … }`) is not the token's value and is skipped.
 */
export function declaredValue(css, name) {
  for (const block of ruleBlocks(css)) {
    if (!isRootRule(block)) continue;
    const m = propPattern(name).exec(block.body);
    if (m) return m[1].trim();
  }
  return null;
}

export function declaredProperties(css) {
  const bare = css.replace(/\/\*[\s\S]*?\*\//g, '');
  return new Set([...bare.matchAll(/(?:^|[{;\s])(--[A-Za-z0-9_-]+)\s*:/g)].map((m) => m[1]));
}

/**
 * How many times `css` declares the custom property `name` at the root — in a
 * rule whose selector list names :root or html (comments stripped). A scoped
 * re-declaration (`.workspace { --tap-floor: … }`) is the cascade doing its
 * job and is not counted; a second root declaration anywhere would override
 * the home's value for the whole page.
 */
export function rootDeclarationCount(css, name) {
  let count = 0;
  for (const block of ruleBlocks(css)) if (isRootRule(block)) count += [...block.body.matchAll(propPattern(name, 'g'))].length;
  return count;
}

/**
 * The flat list of tokens: { group, key, path, name, value, home }.
 * `value` is the CSS text; `home` is the stylesheet that already declares it, if any.
 */
export function tokenEntries(data) {
  const out = [];
  const add = (group, key, path, name, value, entry) => out.push({ group, key, path, name: entry?.css ?? name, value, home: entry?.home ?? null, px: typeof entry?.px === 'number' ? entry.px : null });
  for (const [key, entry] of Object.entries(data.type?.scale ?? {})) {
    add('type', key, `type.scale.${key}`, `--t-${kebab(key)}`, entry.px == null ? null : `${num(entry.px / REM_PX)}rem`, entry);
  }
  for (const [key, z] of Object.entries(data.layer ?? {})) add('layer', key, `layer.${key}`, `--layer-${kebab(key)}`, String(z));
  for (const [key, ms] of Object.entries(data.motion ?? {})) add('motion', key, `motion.${key}`, `--motion-${kebab(key)}`, `${ms}ms`);
  for (const [key, entry] of Object.entries(data.touch ?? {})) {
    add('touch', key, `touch.${key}`, `--touch-${kebab(key.replace(/Px$/, ''))}`, entry.px == null ? null : `${num(entry.px)}px`, entry);
  }
  return out;
}

/** The colour custom properties: { block ('palette' or the theme key), selector, path, name, value, note }. */
export function colorEntries(data) {
  const out = [];
  const color = data.color;
  if (!color) return out;
  for (const [key, value] of Object.entries(color.palette ?? {})) out.push({ block: 'palette', selector: ':root', path: `color.palette.${key}`, name: `--${kebab(key)}`, value, note: color.notes?.[key] ?? null });
  for (const [theme, def] of Object.entries(color.themes ?? {})) {
    for (const [key, value] of Object.entries(def.colors ?? {})) out.push({ block: theme, selector: def.selector, path: `color.themes.${theme}.colors.${key}`, name: `--${kebab(key)}`, value, note: def.notes?.[key] ?? null });
  }
  return out;
}

/** How many times `css` declares `name` in a rule whose selector list includes `selector` exactly. */
function declaredAt(css, selector, name) {
  const bare = css.replace(/\/\*[\s\S]*?\*\//g, '');
  let n = 0;
  for (const m of bare.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    if (!m[1].split(',').some((s) => s.trim().replace(/\s+/g, ' ') === selector)) continue;
    n += [...m[2].matchAll(propPattern(name, 'g'))].length;
  }
  return n;
}

const noteComment = (note, indent) => {
  const lines = note.split('\n').map((l) => l.trimEnd());
  return lines.length === 1 ? ` /* ${lines[0]} */` : `\n${indent}/* ${lines.join(`\n${indent}   `)} */`;
};

const GROUP_TITLES = {
  type: 'type scale (rem: the root is 10px at Text M, so it follows the Text size setting)',
  layer: 'stacking layers (z-index), bottom to top',
  motion: 'motion durations',
  touch: 'touch sizes (px: a finger does not grow with Text size)',
};

/**
 * generateTokensCss(data, { stylesheets }) → { css, errors }.
 * `data` is the parsed tokens.json; `stylesheets` maps a stylesheet path to its
 * text (the homes, plus every stylesheet a published name must not collide with).
 */
export function generateTokensCss(data, { stylesheets = {}, file = TOKENS_JSON } = {}) {
  const errors = tokenGroupProblems('ui/tokens.json', data).map((e) => e.replace('content/config/ui/tokens.json', file));
  if (errors.length) return { css: null, errors };
  const entries = tokenEntries(data);
  const declared = Object.fromEntries(Object.entries(stylesheets).map(([path, text]) => [path, declaredProperties(text)]));
  const seen = new Map();
  for (const e of entries) {
    if (seen.has(e.name)) errors.push(`${file}: ${e.path} and ${seen.get(e.name)} both publish ${e.name}`);
    seen.set(e.name, e.path);
    if (e.home) {
      if (!(e.home in declared)) errors.push(`${file}: ${e.path}.home ${e.home} was not read — it is not a stylesheet this tool knows`);
      else if (!declared[e.home].has(e.name)) errors.push(`${file}: ${e.path}.home says ${e.home} declares ${e.name}, but it does not`);
      else if (rootDeclarationCount(stylesheets[e.home], e.name) !== 1
        || Object.entries(stylesheets).some(([path, text]) => path !== e.home && rootDeclarationCount(text, e.name) > 0)) {
        // One home per fact means one root declaration: a second one in the
        // home (a later rule) or in another stylesheet (which may load later)
        // would override the value the check below verifies. Scoped overrides
        // inside a component are the cascade's business and are not counted.
        const inHome = rootDeclarationCount(stylesheets[e.home], e.name);
        const elsewhere = Object.entries(stylesheets).filter(([path, text]) => path !== e.home && rootDeclarationCount(text, e.name) > 0).map(([path]) => path);
        errors.push(`${file}: ${e.path}.home ${e.home} must hold the only root declaration of ${e.name} — found ${inHome} there${elsewhere.length ? ` and more in ${elsewhere.join(', ')}` : ''}; one home per fact`);
      } else if (e.px != null) {
        // The home owns the value, so tokens.json's px must agree with it
        // (rem at the 10px root; px as px). A calc() or var() home cannot be
        // compared and is reported, so the author drops px there.
        const home = declaredValue(stylesheets[e.home], e.name);
        const px = home == null ? null : /^([\d.]+)rem$/.test(home) ? Number(RegExp.$1) * 10 : /^([\d.]+)px$/.test(home) ? Number(RegExp.$1) : NaN;
        if (px == null) errors.push(`${file}: ${e.path}.home ${e.home} declares ${e.name} but its value could not be read`);
        else if (Number.isNaN(px)) errors.push(`${file}: ${e.path}.px ${e.px} cannot be checked against ${e.home}'s ${e.name}: ${home} — drop px here; the home owns the value`);
        else if (px !== e.px) errors.push(`${file}: ${e.path}.px ${e.px} disagrees with ${e.home}'s ${e.name}: ${home} (${px}px) — one home per fact, change the home`);
      }
    } else {
      for (const [path, names] of Object.entries(declared)) {
        if (names.has(e.name)) errors.push(`${file}: ${e.path} would declare ${e.name}, which ${path} already declares — set "home": "${path}" or rename it`);
      }
    }
  }
  const colours = colorEntries(data);
  const colourSeen = new Map();
  for (const c of colours) {
    const id = `${c.selector} ${c.name}`;
    if (colourSeen.has(id)) errors.push(`${file}: ${c.path} and ${colourSeen.get(id)} both publish ${c.name} under ${c.selector}`);
    colourSeen.set(id, c.path);
    if (c.block === 'palette' && seen.has(c.name)) errors.push(`${file}: ${c.path} and ${seen.get(c.name)} both publish ${c.name}`);
    for (const [path, text] of Object.entries(stylesheets)) {
      const count = c.block === 'palette' ? rootDeclarationCount(text, c.name) : declaredAt(text, c.selector, c.name);
      if (count > 0) errors.push(`${file}: ${c.path} would declare ${c.name} under ${c.selector}, which ${path} already declares there — delete it from ${path} (one home per fact)`);
    }
  }
  if (errors.length) return { css: null, errors };

  const lines = [HEADER, ':root {'];
  for (const group of ['type', 'layer', 'motion', 'touch']) {
    const own = entries.filter((e) => e.group === group && !e.home);
    const homed = entries.filter((e) => e.group === group && e.home);
    if (!own.length && !homed.length) continue;
    lines.push(`  /* ${GROUP_TITLES[group]} */`);
    for (const e of own) lines.push(`  ${e.name}: ${e.value};`);
    if (homed.length) lines.push(`  /* already declared where they live, not repeated: ${homed.map((e) => `${e.name} (${e.home})`).join(', ')} */`);
  }
  const own = colours.filter((c) => c.block === 'palette');
  if (own.length) {
    lines.push('  /* colours */');
    for (const c of own) lines.push(`  ${c.name}: ${c.value};${c.note ? noteComment(c.note, '  ') : ''}`);
  }
  lines.push('}');
  for (const [theme, def] of Object.entries(data.color?.themes ?? {})) {
    lines.push(`/* colour theme: ${theme} */`, `${def.selector} {`);
    for (const c of colours.filter((e) => e.block === theme)) lines.push(`  ${c.name}: ${c.value};${c.note ? noteComment(c.note, '  ') : ''}`);
    lines.push('}');
  }
  return { css: lines.join('\n') + '\n', errors };
}

/** Reads tokens.json and the stylesheets from `root` and generates the CSS. */
export function buildTokensCss(root = ROOT) {
  const jsonPath = resolve(root, TOKENS_JSON);
  if (!existsSync(jsonPath)) return { css: null, errors: [`${TOKENS_JSON}: missing`] };
  let data;
  try { data = JSON.parse(readFileSync(jsonPath, 'utf8')); }
  catch (error) { return { css: null, errors: [`${TOKENS_JSON}: not valid JSON — ${error.message}`] }; }
  // Every authored stylesheet except the file this tool writes: a published name
  // another sheet already declares is a second home for the fact.
  const stylesheets = {};
  const dir = resolve(root, 'styles');
  if (existsSync(dir)) {
    for (const name of readdirSync(dir).sort()) {
      if (!name.endsWith('.css') || `styles/${name}` === TOKENS_CSS) continue;
      stylesheets[`styles/${name}`] = readFileSync(resolve(dir, name), 'utf8');
    }
  }
  return generateTokensCss(data, { stylesheets });
}

function main(argv) {
  const check = argv.includes('--check');
  const unknown = argv.filter((arg) => !['--check', '--write'].includes(arg));
  if (unknown.length) { console.error(`tokens-css: unknown argument(s) ${unknown.join(' ')}`); return 2; }
  const { css, errors } = buildTokensCss(ROOT);
  if (errors.length) {
    console.error(`tokens-css: REFUSED — ${errors.length} problem(s):\n  ${errors.join('\n  ')}`);
    return 1;
  }
  const out = resolve(ROOT, TOKENS_CSS);
  const current = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : null;
  if (check) {
    if (current !== css) {
      console.error(`STALE: ${TOKENS_CSS} does not match ${TOKENS_JSON} — run node tools/tokens-css.mjs --write`);
      return 1;
    }
    console.log(`tokens-css: ${TOKENS_CSS} is current with ${TOKENS_JSON}`);
    return 0;
  }
  if (current !== css) writeFileSync(out, css);
  console.log(`tokens-css: ${current === css ? 'unchanged' : 'wrote'} ${TOKENS_CSS}`);
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) process.exit(main(process.argv.slice(2)));
