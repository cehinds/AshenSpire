#!/usr/bin/env node
// Compile authored calculation mechanics into the browser graph. Definitions
// stay in the existing mechanic folders; never hand-maintain JS defaults.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { loadMechanics } from '../engine/runtime/interpreter.mjs';
import { validateModifiers, parameterDefaults, validateParameters } from '../engine/runtime/bindings.mjs';
export function browserMechanics() {
  return [...loadMechanics()].filter(([, m]) => m.manifest.authored && m.service.modifiers?.some(row => row.phase)).map(([id,m]) => {
    validateModifiers(m.service.modifiers, `engine/mechanics/${id}/service.json.modifiers`);
    validateParameters(m.manifest.parameters, parameterDefaults(m.manifest.parameters), `engine/mechanics/${id}/mechanic.json.parameters`);
    return [id, { manifest: m.manifest, service: m.service }];
  });
}
export function compileBrowserMechanics({check = false} = {}) {
  const file = new URL('../src/content/generated/fixCoreProtection.js', import.meta.url);
  const text = '// GENERATED by tools/mechanics-browser.mjs from engine/mechanics/*/*.json\nexport const fixCoreProtection = '+JSON.stringify(browserMechanics(), null, 2)+';\n';
  let old = ''; try { old = readFileSync(file, 'utf8'); } catch {}
  if (old === text) return false;
  if (check) throw new Error(`${fileURLToPath(file)} is stale; run node tools/mechanics-browser.mjs`);
  writeFileSync(file, text); return true;
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  compileBrowserMechanics({check: process.argv.includes('--check')});
  console.log('browser mechanics: current');
}
