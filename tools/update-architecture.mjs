#!/usr/bin/env node
// Refresh the current-dev architecture inventory without rewriting the core
// architecture contracts. The GitHub workflow runs this after every push to
// dev, including a merge push.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = resolve(ROOT, 'docs/ARCHITECTURE-CURRENT-DEV.md');
const CHECK = process.argv.includes('--check');
const VERIFY = process.argv.includes('--verify');

function git(...args) {
  return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' }).trim();
}

function trackedFiles() {
  return git('ls-files').split(/\r?\n/).filter(Boolean);
}

function filesUnder(files, prefix) {
  return files.filter((file) => file.startsWith(prefix));
}

function countExtensions(files) {
  const counts = new Map();
  for (const file of files) {
    const match = file.match(/\.([^.]+)$/);
    const extension = match ? `.${match[1].toLowerCase()}` : '(none)';
    counts.set(extension, (counts.get(extension) || 0) + 1);
  }
  return [...counts.entries()].sort(([a], [b]) => a.localeCompare(b));
}

function readSourceFiles(files, prefix) {
  return filesUnder(files, prefix)
    .filter((file) => file.endsWith('.js'))
    .map((file) => ({ file, text: readFileSync(resolve(ROOT, file), 'utf8') }));
}

function stripComments(text) {
  return text
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|\s)\/\/.*$/gm, '$1');
}

function boundaryFindings(files, prefix, pattern) {
  const findings = [];
  for (const { file, text } of readSourceFiles(files, prefix)) {
    const clean = stripComments(text);
    if (pattern.test(clean)) findings.push(file);
    pattern.lastIndex = 0;
  }
  return findings;
}

const files = trackedFiles();
const sourceSha = process.env.ARCHITECTURE_SOURCE_SHA || git('rev-parse', 'HEAD');
const sourceBranch = process.env.ARCHITECTURE_SOURCE_REF
  || process.env.GITHUB_REF_NAME
  || git('branch', '--show-current')
  || 'detached';

const areas = [
  ['Domain models and contracts', 'src/model/'],
  ['Headless simulation/services', 'src/engine/'],
  ['Screen presenters/hosts', 'src/ui/screens/'],
  ['Presentation projections', 'src/ui/viewModels/'],
  ['Component models and behavior records', 'src/ui/models/'],
  ['DOM components and observer adapters', 'src/ui/components/'],
  ['Code-side content adapters', 'src/content/'],
  ['Authoritative JSON/CSV content', 'content/source/'],
  ['Transport', 'src/net/'],
  ['Tests', 'tests/'],
  ['Architecture/tooling', 'tools/'],
];

const engineDomFindings = boundaryFindings(
  files,
  'src/engine/',
  /\b(?:document|window|localStorage|setTimeout|setInterval)\b/g,
);
const modelDomFindings = boundaryFindings(
  files,
  'src/model/',
  /\b(?:document|window|localStorage)\b/g,
);
const engineUiImportFindings = boundaryFindings(
  files,
  'src/engine/',
  /from\s+['"][^'"]*\/(?:ui|screens)\//g,
);
const requiredDocs = [
  'docs/ARCHITECTURE-MAP.md',
  'docs/COMPONENT-MODEL-ARCHITECTURE.md',
];
const missingDocs = requiredDocs.filter((file) => !existsSync(resolve(ROOT, file)));
const coreText = requiredDocs
  .filter((file) => existsSync(resolve(ROOT, file)))
  .map((file) => readFileSync(resolve(ROOT, file), 'utf8').toLowerCase())
  .join('\n');
const requiredCoreMarkers = [
  'composition/component-based',
  'mvp',
  'observer',
  'json/csv',
  'source of truth',
];
const missingCoreMarkers = requiredCoreMarkers.filter((marker) => !coreText.includes(marker));
const jsonCsv = filesUnder(files, 'content/source/').filter((file) => /\.(json|csv)$/i.test(file));
const jsonCount = jsonCsv.filter((file) => file.toLowerCase().endsWith('.json')).length;
const csvCount = jsonCsv.filter((file) => file.toLowerCase().endsWith('.csv')).length;
const boundaryChecks = [
  ['engine has no browser host references', engineDomFindings.length === 0],
  ['model has no DOM/storage references', modelDomFindings.length === 0],
  ['engine has no UI imports', engineUiImportFindings.length === 0],
  ['core architecture contracts exist', missingDocs.length === 0],
  ['core redesign markers remain present', missingCoreMarkers.length === 0],
];
const boundaryStatus = boundaryChecks.every(([, ok]) => ok) ? 'PASS' : 'REVIEW';

const lines = [
  '# AshenSpire current `dev` architecture snapshot',
  '',
  '> Generated by `tools/update-architecture.mjs`. This inventory changes with',
  '> `dev`; the stable redesign contract remains in [`ARCHITECTURE-MAP.md`](./ARCHITECTURE-MAP.md)',
  '> and [`COMPONENT-MODEL-ARCHITECTURE.md`](./COMPONENT-MODEL-ARCHITECTURE.md).',
  '',
  `- Source branch: \`${sourceBranch}\``,
  `- Source commit: \`${sourceSha}\``,
  `- Boundary status: **${boundaryStatus}**`,
  '',
  '## Core architecture that this refresh must preserve',
  '',
  '- Composition/component-based ownership remains the primary structure.',
  '- Presenters project immutable Component Models; components render and bind.',
  '- Simulation and domain rules remain headless and DOM-free.',
  '- Observer-style adapters stay at input, lifecycle, refresh, and browser seams.',
  '- JSON/CSV data and reusable interpreters remain the content path.',
  '- MVC/MVVM are not introduced as framework or folder requirements.',
  '',
  '## Current ownership inventory',
  '',
  '| Area | Path | Tracked files |',
  '|---|---|---:|',
  ...areas.map(([label, prefix]) => `| ${label} | \`${prefix}\` | ${filesUnder(files, prefix).length} |`),
  '',
  '## Current implementation signals',
  '',
  '- Composition root: `src/main.js`.',
  '- Shared presentation projection: `src/ui/viewModels/RunHudViewModel.js`.',
  '- Immutable presentation records: `src/ui/models/ComponentModel.js` and `BehaviorModel.js`.',
  '- Headless simulation boundary: `src/engine/` imports model/content, not UI/screens.',
  `- Authoritative content inputs: ${jsonCount} JSON file(s) and ${csvCount} CSV file(s) under \`content/source/\`.`,
  '',
  '## Automated boundary checks',
  '',
  ...boundaryChecks.map(([label, ok]) => `- ${ok ? 'PASS' : 'REVIEW'} — ${label}.`),
  ...(engineDomFindings.length ? [`  - Findings: ${engineDomFindings.map((file) => `\`${file}\``).join(', ')}.`] : []),
  ...(modelDomFindings.length ? [`  - Findings: ${modelDomFindings.map((file) => `\`${file}\``).join(', ')}.`] : []),
  ...(engineUiImportFindings.length ? [`  - Findings: ${engineUiImportFindings.map((file) => `\`${file}\``).join(', ')}.`] : []),
  ...(missingDocs.length ? [`  - Missing: ${missingDocs.map((file) => `\`${file}\``).join(', ')}.`] : []),
  ...(missingCoreMarkers.length ? [`  - Missing core markers: ${missingCoreMarkers.map((marker) => `\`${marker}\``).join(', ')}.`] : []),
  '',
  '## File-shape summary',
  '',
  `Tracked files: **${files.length}**.`,
  `Extensions: ${countExtensions(files).map(([extension, count]) => `\`${extension}\` ${count}`).join(', ')}.`,
  '',
  'This file is an inventory, not architecture authority. A refresh may update',
  'the counts, source commit, and observed signals, but it must not rewrite the',
  'core contract or change the redesign goals.',
  '',
];
const generated = lines.join('\n');

if (CHECK) {
  const existing = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : '';
  if (existing !== generated) {
    console.error(`ARCHITECTURE SNAPSHOT OUT OF DATE: ${OUTPUT}`);
    process.exitCode = 1;
  } else {
    console.log(`ARCHITECTURE SNAPSHOT CURRENT: ${sourceSha}`);
  }
} else {
  const existing = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : '';
  if (existing !== generated) writeFileSync(OUTPUT, generated, 'utf8');
  console.log(`${existing === generated ? 'ARCHITECTURE SNAPSHOT UNCHANGED' : 'ARCHITECTURE SNAPSHOT UPDATED'}: ${sourceSha}`);
}

if (VERIFY && boundaryStatus !== 'PASS') {
  console.error('ARCHITECTURE BOUNDARY REVIEW REQUIRED');
  process.exitCode = 1;
}
