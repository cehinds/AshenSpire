// node --test workbench/tests/tag-model-rules.test.mjs — the tag model editability map:
// which table is authored, mixed, presentation or generated, which job a save runs,
// and which derived cells or read-only rows a save may not change.
import test from 'node:test';
import assert from 'node:assert/strict';
import { TAG_MODEL_EDITABLE, tagModelTable, tagModelSavable, tagModelJobFor, checkTagModelSave } from '../core/tag-model.mjs';

const D = 'docs/tag-model/tables';

test('the map names the authored, mixed and presentation tables, and their jobs', () => {
  assert.equal(tagModelTable(`${D}/values.csv`).tier, 'authored');
  assert.equal(tagModelTable(`${D}/values.csv`).job, 'tag-model-check');
  assert.equal(tagModelTable(`${D}/tags.csv`).tier, 'mixed');
  assert.equal(tagModelTable(`${D}/tags.csv`).job, 'tag-model');
  assert.deepEqual(tagModelTable(`${D}/tags.csv`).readOnlyColumns, ['key', 'status', 'liveId']);
  assert.deepEqual(tagModelTable(`${D}/objects.csv`).refColumns, ['tags', 'skill', 'exp', 'cardType', 'stance', 'rarity', 'costResource']);
  assert.deepEqual(tagModelTable(`${D}/relations.csv`).refColumns, ['source', 'target']);
  const layouts = tagModelTable(`${D}/presentation/layouts.csv`);
  assert.equal(layouts.tier, 'presentation');
  assert.equal(layouts.job, 'tag-model');
  assert.match(layouts.banner, /A re-extraction \(build\.mjs --inv\) overwrites these columns/);
  assert.ok(layouts.readOnlyColumns.includes('band'));
  assert.ok(!layouts.readOnlyColumns.includes('artBrief') && !layouts.readOnlyColumns.includes('priority'), 'artBrief and priority are authored columns of combat-symbols.csv');
});

test('root assets.csv is authored, presentation/assets.csv is presentation', () => {
  assert.equal(tagModelTable(`${D}/assets.csv`).tier, 'authored');
  assert.equal(tagModelTable(`${D}/presentation/assets.csv`).tier, 'presentation');
});

test('a CSV the map does not name is generated: shown read-only with the generated note', () => {
  const rule = tagModelTable(`${D}/something-new.csv`);
  assert.equal(rule.tier, 'generated');
  assert.equal(tagModelSavable(rule), false);
  assert.match(rule.banner, /^Generated by docs\/tag-model\/tools\/build\.mjs\. Run the Tag model job to refresh\.$/);
});

test('paths outside the tables folder, non-CSV files and traversal are not tag-model tables', () => {
  assert.equal(tagModelTable('docs/tag-model/README.md'), null);
  assert.equal(tagModelTable(`${D}/values.json`), null);
  assert.equal(tagModelTable(`${D}/../tag-tree.csv`), null);
  assert.equal(tagModelTable(`${D}/presentation/deep/x.csv`).tier, 'generated');
  assert.equal(tagModelTable('content/source/nodes.csv'), null);
});

test('a save runs the full job when any mixed or presentation table is in it, else the check', () => {
  assert.equal(tagModelJobFor([`${D}/values.csv`]), 'tag-model-check');
  assert.equal(tagModelJobFor([`${D}/values.csv`, `${D}/tags.csv`]), 'tag-model');
  assert.equal(tagModelJobFor([`${D}/presentation/strings.csv`]), 'tag-model');
  assert.equal(tagModelJobFor([]), null);
});

test('an injected map replaces the default one', () => {
  const map = { ...TAG_MODEL_EDITABLE, authored: { job: 'tag-model-check', files: ['only.csv'] } };
  assert.equal(tagModelTable(`${D}/only.csv`, map).tier, 'authored');
  assert.equal(tagModelTable(`${D}/values.csv`, map).tier, 'generated');
});

test('an authored table accepts any change, including a new row and a removed row', () => {
  const rule = tagModelTable(`${D}/values.csv`);
  const disk = 'id,value\nar,24\nhp,10\n';
  assert.deepEqual(checkTagModelSave(rule, 'id,value\nar,30\nnew,1\n', disk), []);
  assert.deepEqual(checkTagModelSave(rule, 'id,value\nar,24\n', disk), []);
});

test('a presentation table refuses a changed derived cell and names it, and accepts a changed base cell', () => {
  const rule = tagModelTable(`${D}/presentation/layouts.csv`);
  const disk = 'id,tag,band,width\nl1,desk,desktop,100\nl2,phone,mobile,50\n';
  const bad = checkTagModelSave(rule, 'id,tag,band,width\nl1,desk,wide,100\nl2,phone,mobile,70\n', disk, 'docs/tag-model/tables/presentation/layouts.csv');
  assert.deepEqual(bad, [{ path: 'docs/tag-model/tables/presentation/layouts.csv', message: 'row l1, band: read-only column' }]);
  assert.deepEqual(checkTagModelSave(rule, 'id,tag,band,width\nl1,desk,desktop,999\nl2,phone,mobile,50\n', disk), []);
});

test('a new presentation row must leave its derived cells blank', () => {
  const rule = tagModelTable(`${D}/presentation/layouts.csv`);
  const disk = 'id,tag,band,width\nl1,desk,desktop,100\n';
  assert.deepEqual(checkTagModelSave(rule, 'id,tag,band,width\nl1,desk,desktop,100\nl3,,,20\n', disk), []);
  assert.equal(checkTagModelSave(rule, 'id,tag,band,width\nl1,desk,desktop,100\nl3,x,,20\n', disk).length, 1);
});

test('tags.csv refuses a change to key, status or liveId, and any change to a meta.presentation row', () => {
  const rule = tagModelTable(`${D}/tags.csv`);
  const disk = 'id,key,label,status,liveId\ncard.strike,strike,Strike,live,7\nmeta.presentation.hud,hud,HUD,meta,\n';
  const saved = 'id,key,label,status,liveId\ncard.strike,strike2,Strike,live,8\nmeta.presentation.hud,hud,HUD changed,meta,\n';
  const problems = checkTagModelSave(rule, saved, disk).map((p) => p.message);
  assert.deepEqual(problems, [
    'row card.strike, key: read-only column',
    'row card.strike, liveId: read-only column',
    'row meta.presentation.hud, label: this row is read-only',
  ]);
  assert.deepEqual(checkTagModelSave(rule, 'id,key,label,status,liveId\ncard.strike,strike,Strike renamed,live,7\nmeta.presentation.hud,hud,HUD,meta,\n', disk), []);
});

test('a read-only row cannot be removed, and a removed editable row is fine', () => {
  const rule = tagModelTable(`${D}/tags.csv`);
  const disk = 'id,key,label,status,liveId\ncard.strike,strike,Strike,live,7\nmeta.presentation.hud,hud,HUD,meta,\n';
  assert.deepEqual(checkTagModelSave(rule, 'id,key,label,status,liveId\ncard.strike,strike,Strike,live,7\n', disk).map((p) => p.message), [
    'row meta.presentation.hud: this row is read-only and cannot be removed',
  ]);
  assert.deepEqual(checkTagModelSave(rule, 'id,key,label,status,liveId\nmeta.presentation.hud,hud,HUD,meta,\n', disk), []);
});

test('a changed header is refused in every tag-model table', () => {
  const rule = tagModelTable(`${D}/values.csv`);
  const problems = checkTagModelSave(rule, 'id,value,extra\nar,24,1\n', 'id,value\nar,24\n');
  assert.equal(problems.length, 1);
  assert.match(problems[0].message, /header row/);
});
