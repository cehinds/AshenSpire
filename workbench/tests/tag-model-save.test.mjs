// node --test workbench/tests/tag-model-save.test.mjs — the file service against a
// fixture docs/tag-model/tables folder: a generated table is refused (403), a read-only
// cell is refused (422, naming the cell), an authored table is saved, and a save of a
// tag-model table is not a game build input.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { allowedKind, createFileService } from '../core/files.mjs';
import { buildsFor } from '../core/watch.mjs';
import { hash } from '../../editor/core.mjs';
import { parseTagCSV, writeTagCSV } from '../lib/tag-model-csv.mjs';

const T = 'docs/tag-model/tables';
const SETTINGS = `${T}/presentation/settings.csv`;
// Three real lines of presentation/settings.csv: its header and a row whose default cell is multiline.
const SETTINGS_TEXT = readFileSync(new URL('./fixtures/tag-model/settings-sample.csv', import.meta.url), 'utf8');
// The settings text with one cell changed, written back in the file's own shape.
const settingsWith = (edit) => {
  const table = parseTagCSV(SETTINGS_TEXT);
  const shape = { eol: table.eol, trailingNewline: table.trailingNewline, bom: table.bom };
  return writeTagCSV({ columns: table.columns, rows: table.rows.map((row, i) => (i === 0 ? { ...row, ...edit } : row)) }, shape);
};
const LAYOUTS = `${T}/presentation/layouts.csv`;
const LAYOUTS_TEXT = 'id,tag,band,width\nl1,desk,desktop,100\nl2,phone,mobile,50\n';

async function fixture(t) {
  const root = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), 'wb-tag-model-')));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  await fs.mkdir(path.join(root, T, 'presentation'), { recursive: true });
  await fs.mkdir(path.join(root, 'content/source'), { recursive: true });
  await fs.writeFile(path.join(root, `${T}/values.csv`), 'id,value\nar,24\n');
  await fs.writeFile(path.join(root, `${T}/tags.csv`), 'id,key,label,status,liveId\ncard.strike,strike,Strike,live,7\nmeta.presentation.hud,hud,HUD,meta,\n');
  await fs.writeFile(path.join(root, LAYOUTS), LAYOUTS_TEXT);
  await fs.writeFile(path.join(root, `${T}/tag-tree.csv`), 'id,label\nx,y\n');
  await fs.writeFile(path.join(root, 'content/source/items.csv'), 'id,name\nsword,Sword\n');
  const stateDir = path.join(root, '.wb-state');
  const saved = [];
  const files = createFileService({ root, stateDir, onSaved: (paths) => saved.push(...paths), lockWaitMs: 2000 });
  const read = async (rel) => {
    const buf = await fs.readFile(path.join(root, rel));
    return { text: buf.toString('utf8'), baseHash: hash(buf) };
  };
  const change = async (rel, text) => ({ path: rel, text, baseHash: (await read(rel)).baseHash });
  return { root, files, saved, change, read };
}

const refused = async (promise, status) => {
  await assert.rejects(promise, (e) => e.status === status, `expected HTTP ${status}`);
  return promise.catch((e) => e);
};

test('the tag-model tables are readable, the generated one included, and only the tables folder counts', () => {
  assert.equal(allowedKind(`${T}/values.csv`), 'csv');
  assert.equal(allowedKind(LAYOUTS), 'csv');
  assert.equal(allowedKind(`${T}/tag-tree.csv`), 'csv', 'read-only tables are still listed and readable');
  assert.equal(allowedKind(`${T}/values.json`), null);
  assert.equal(allowedKind('docs/tag-model/README.md'), null);
});

test('an authored table is saved', async (t) => {
  const f = await fixture(t);
  const change = await f.change(`${T}/values.csv`, 'id,value\nar,30\nhp,10\n');
  const result = await f.files.save([change]);
  assert.equal(result.files[0].path, `${T}/values.csv`);
  assert.equal(await fs.readFile(path.join(f.root, `${T}/values.csv`), 'utf8'), 'id,value\nar,30\nhp,10\n');
  assert.deepEqual(f.saved, [`${T}/values.csv`]);
});

test('a generated table is refused with 403 and writes nothing', async (t) => {
  const f = await fixture(t);
  const change = await f.change(`${T}/tag-tree.csv`, 'id,label\nx,changed\n');
  const err = await refused(f.files.save([change]), 403);
  assert.match(err.message, /generated by docs\/tag-model\/tools\/build\.mjs/);
  assert.equal(await fs.readFile(path.join(f.root, `${T}/tag-tree.csv`), 'utf8'), 'id,label\nx,y\n');
  assert.deepEqual(f.saved, []);
});

test('a save that changes a derived cell is refused with 422, naming the cell, and writes nothing', async (t) => {
  const f = await fixture(t);
  const change = await f.change(LAYOUTS, 'id,tag,band,width\nl1,desk,wide,100\nl2,phone,mobile,50\n');
  const err = await refused(f.files.save([change]), 422);
  assert.equal(err.problems.length, 1);
  assert.equal(err.problems[0].path, LAYOUTS);
  assert.equal(err.problems[0].message, 'row l1, band: read-only column');
  assert.equal(await fs.readFile(path.join(f.root, LAYOUTS), 'utf8'), LAYOUTS_TEXT);
  assert.deepEqual(f.saved, []);
});

test('a save that edits a base cell of a presentation table is accepted', async (t) => {
  const f = await fixture(t);
  const change = await f.change(LAYOUTS, 'id,tag,band,width\nl1,desk,desktop,640\nl2,phone,mobile,50\n');
  await f.files.save([change]);
  assert.match(await fs.readFile(path.join(f.root, LAYOUTS), 'utf8'), /l1,desk,desktop,640/);
});

test('a save that removes a read-only tags.csv row is refused with 422', async (t) => {
  const f = await fixture(t);
  const change = await f.change(`${T}/tags.csv`, 'id,key,label,status,liveId\ncard.strike,strike,Strike,live,7\n');
  const err = await refused(f.files.save([change]), 422);
  assert.equal(err.problems[0].message, 'row meta.presentation.hud: this row is read-only and cannot be removed');
});

test('a tag-model save is not a game build input: no build step, no content lock', async (t) => {
  const f = await fixture(t);
  const change = await f.change(`${T}/values.csv`, 'id,value\nar,31\n');
  await f.files.save([change]);
  assert.deepEqual(buildsFor(f.saved, f.root), [], 'the game build has no step for a docs/tag-model save');
});

test('a read of a tag-model table says its tier, whether it is savable, and its banner', async (t) => {
  const f = await fixture(t);
  const generated = await f.files.read(`${T}/tag-tree.csv`);
  assert.equal(generated.tagModel.tier, 'generated');
  assert.equal(generated.tagModel.savable, false);
  assert.equal(generated.tagModel.banner, 'Generated by docs/tag-model/tools/build.mjs. Run the Tag model job to refresh.');
  const layouts = await f.files.read(LAYOUTS);
  assert.equal(layouts.tagModel.tier, 'presentation');
  assert.equal(layouts.tagModel.savable, true);
  assert.equal(layouts.tagModel.job, 'tag-model');
  assert.match(layouts.tagModel.banner, /A re-extraction \(build\.mjs --inv\) overwrites these columns/);
  assert.equal((await f.files.read('content/source/items.csv')).tagModel, undefined);
});

test('a multiline table saves: a base edit to a multiline row is accepted and the file keeps its multiline cell', async (t) => {
  const f = await fixture(t);
  await fs.writeFile(path.join(f.root, SETTINGS), SETTINGS_TEXT);
  const change = await f.change(SETTINGS, settingsWith({ label: 'Narration' }));
  await f.files.save([change]);
  const disk = await fs.readFile(path.join(f.root, SETTINGS), 'utf8');
  assert.match(disk, /^gameConfig\.prologue\.scenes\.warmth\.text,Narration,/m);
  assert.equal(parseTagCSV(disk).rows[0].default, 'Three hearths once kept the roads warm.\nWe lived beyond their walls.');
});

test('a single-line save over a multiline disk file still runs the rules: a changed derived cell is refused', async (t) => {
  const f = await fixture(t);
  await fs.writeFile(path.join(f.root, SETTINGS), SETTINGS_TEXT);
  // The page sends the row's default as one line (no line break), and changes its tag (a read-only column).
  const change = await f.change(SETTINGS, settingsWith({ default: 'Short line', tag: 'player.changed' }));
  const err = await refused(f.files.save([change]), 422);
  assert.deepEqual(err.problems.map((p) => p.message), ['row 1, tag: read-only column']);
  assert.equal(await fs.readFile(path.join(f.root, SETTINGS), 'utf8'), SETTINGS_TEXT, 'nothing is written');
});

test('a single-line save of a base cell over a multiline disk file is accepted', async (t) => {
  const f = await fixture(t);
  await fs.writeFile(path.join(f.root, SETTINGS), SETTINGS_TEXT);
  await f.files.save([await f.change(SETTINGS, settingsWith({ default: 'Short line' }))]);
  assert.equal(parseTagCSV(await fs.readFile(path.join(f.root, SETTINGS), 'utf8')).rows[0].default, 'Short line');
});

test('an unparseable disk file refuses the save with the parse message, and writes nothing', async (t) => {
  const f = await fixture(t);
  const broken = 'key,label\nbroken,"never closed\n';
  await fs.writeFile(path.join(f.root, SETTINGS), broken);
  const change = await f.change(SETTINGS, SETTINGS_TEXT);
  const err = await refused(f.files.save([change]), 422);
  assert.equal(err.problems.length, 1);
  assert.equal(err.problems[0].path, SETTINGS);
  assert.match(err.problems[0].message, /^The file on disk does not parse: Unclosed CSV quote/);
  assert.equal(await fs.readFile(path.join(f.root, SETTINGS), 'utf8'), broken);
  assert.deepEqual(f.saved, []);
});

test('an unparseable new text is refused with 422 and its parse message, listed once', async (t) => {
  const f = await fixture(t);
  await fs.writeFile(path.join(f.root, SETTINGS), SETTINGS_TEXT);
  const change = await f.change(SETTINGS, 'key,label\nbroken,"never closed\n');
  const err = await refused(f.files.save([change]), 422);
  assert.deepEqual(err.problems, [{ path: SETTINGS, message: 'Unclosed CSV quote at line 2.' }]);
  assert.equal(await fs.readFile(path.join(f.root, SETTINGS), 'utf8'), SETTINGS_TEXT);
});
