// workbench/core/tag-model.mjs — the editability rules for the tag model proposal
// (docs/tag-model/tables, from feature/TagRefactor). Pure: no file reads here, so
// the rules can be injected in tests and the map is the one place to extend.
//
// Three tiers. A table the map does not name is read-only (its banner says it is
// generated). The tables are re-extracted by docs/tag-model/tools/build.mjs, so a
// save runs the job that keeps them consistent after it.
import { parseCSV } from '../../editor/tables.mjs';

export const TAG_MODEL_DIR = 'docs/tag-model/tables';
export const TAG_MODEL_JOBS = { check: 'tag-model-check', full: 'tag-model' };
export const TAG_MODEL_GENERATED_NOTE = 'Generated by docs/tag-model/tools/build.mjs. Run the Tag model job to refresh.';

/** The editability map. Edit this list to change which cells a save may touch. */
export const TAG_MODEL_EDITABLE = {
  // Every column is editable; a save runs the check job.
  authored: { job: TAG_MODEL_JOBS.check, files: ['values.csv', 'formulas.csv', 'ranks.csv', 'assets.csv'] },
  // Some columns are derived, and build may rewrite tag-key references, so a save runs the full job.
  mixed: {
    job: TAG_MODEL_JOBS.full,
    files: {
      'tags.csv': {
        readOnlyColumns: ['key', 'status', 'liveId'],
        readOnlyRows: { column: 'id', prefix: 'meta.presentation' },
        note: 'key, status and liveId are derived. Rows whose id starts with meta.presentation are read-only.',
      },
      'objects.csv': {
        refColumns: ['tags', 'skill', 'exp', 'cardType', 'stance', 'rarity', 'costResource'],
        note: 'Build may rewrite tag-key references in: tags, skill, exp, cardType, stance, rarity, costResource.',
      },
      'relations.csv': {
        refColumns: ['source', 'target'],
        note: 'Build may rewrite tag-key references in: source, target.',
      },
    },
  },
  // Base columns are editable; the derived ones are read-only. Every presentation/*.csv is in this tier.
  presentation: {
    job: TAG_MODEL_JOBS.full,
    dir: 'presentation/',
    banner: 'A re-extraction (build.mjs --inv) overwrites these columns',
    readOnlyColumns: ['tag', 'liveRef', 'band', 'scope', 'deviceScope', 'assignedAssetRef', 'status', 'cssClasses', 'cssComponentId', 'proposedKey', 'migrateTo'],
  },
};

/** The rule for a table path (repo-relative, e.g. docs/tag-model/tables/values.csv), or null when it is not a tag-model CSV. */
export function tagModelTable(rel, map = TAG_MODEL_EDITABLE) {
  if (typeof rel !== 'string' || !rel.startsWith(`${TAG_MODEL_DIR}/`) || !/\.csv$/i.test(rel)) return null;
  const table = rel.slice(TAG_MODEL_DIR.length + 1); // 'values.csv' or 'presentation/layouts.csv'
  if (!/^(?:[\w-]+\/)*[\w-]+\.csv$/i.test(table)) return null;
  if (map.authored.files.includes(table)) return { table, tier: 'authored', job: map.authored.job, readOnlyColumns: [], readOnlyRows: null, refColumns: [], banner: '', note: '' };
  if (Object.hasOwn(map.mixed.files, table)) {
    const m = map.mixed.files[table];
    return { table, tier: 'mixed', job: map.mixed.job, readOnlyColumns: m.readOnlyColumns ?? [], readOnlyRows: m.readOnlyRows ?? null, refColumns: m.refColumns ?? [], banner: '', note: m.note ?? '' };
  }
  if (table.startsWith(map.presentation.dir) && !table.slice(map.presentation.dir.length).includes('/')) {
    return { table, tier: 'presentation', job: map.presentation.job, readOnlyColumns: map.presentation.readOnlyColumns, readOnlyRows: null, refColumns: [], banner: map.presentation.banner, note: '' };
  }
  // A CSV under the folder that the map does not name: it is shown, but read-only.
  return { table, tier: 'generated', job: null, readOnlyColumns: [], readOnlyRows: null, refColumns: [], banner: TAG_MODEL_GENERATED_NOTE, note: '' };
}

/** Whether a save may write this table at all: every tier except the unlisted, generated one. */
export const tagModelSavable = (rule) => Boolean(rule && rule.tier !== 'generated');

/** The job a save of these paths runs: the full job when any mixed or presentation table is in it, else the check, else none. */
export function tagModelJobFor(paths = [], map = TAG_MODEL_EDITABLE) {
  const rules = paths.map((p) => tagModelTable(p, map)).filter(Boolean);
  if (rules.some((r) => r.job === TAG_MODEL_JOBS.full)) return TAG_MODEL_JOBS.full;
  if (rules.some((r) => r.job === TAG_MODEL_JOBS.check)) return TAG_MODEL_JOBS.check;
  return null;
}

/** Problems with a save of one tag-model table: [{ path, message }], one per cell or row the save may not change.
 *  savedText is the text the page sends; diskText is the file on disk ('' when it is new). Rows are matched by `id`,
 *  or by position when the table has no id column. Only the derived columns and the read-only rows are checked. */
export function checkTagModelSave(rule, savedText, diskText = '', path = `${TAG_MODEL_DIR}/${rule.table}`) {
  const saved = parseCSV(savedText);
  const disk = diskText && diskText.trim() ? parseCSV(diskText) : { columns: saved.columns, rows: [] };
  const problems = [];
  const at = (message) => problems.push({ path, message });
  if (disk.columns.join('\u0001') !== saved.columns.join('\u0001')) {
    at('The header row and its column order cannot change. Keep the columns as they are.');
    return problems;
  }
  const keyed = saved.columns.includes('id');
  const keyOf = (row, i) => (keyed ? String(row.id) : `#${i}`);
  const labelOf = (row, i) => (keyed ? `row ${row.id}` : `row ${i + 1}`);
  const diskRows = new Map(disk.rows.map((row, i) => [keyOf(row, i), row]));
  const isReadOnlyRow = (row) => {
    const r = rule.readOnlyRows;
    return Boolean(r && String(row[r.column] ?? '').startsWith(r.prefix));
  };
  const readOnlyCols = rule.readOnlyColumns.filter((c) => saved.columns.includes(c));
  const seen = new Set();
  saved.rows.forEach((row, i) => {
    const key = keyOf(row, i);
    seen.add(key);
    const base = diskRows.get(key) ?? null;
    const label = labelOf(row, i);
    if (isReadOnlyRow(row)) {
      if (!base) at(`${label}: this row is read-only and cannot be added`);
      else for (const col of saved.columns) if ((row[col] ?? '') !== (base[col] ?? '')) at(`${label}, ${col}: this row is read-only`);
      return;
    }
    for (const col of readOnlyCols) {
      if ((row[col] ?? '') !== (base ? base[col] ?? '' : '')) at(`${label}, ${col}: read-only column`);
    }
  });
  disk.rows.forEach((row, i) => {
    if (isReadOnlyRow(row) && !seen.has(keyOf(row, i))) at(`${labelOf(row, i)}: this row is read-only and cannot be removed`);
  });
  return problems;
}

/** What the Data Studio page needs to show a tag-model table: its tier, whether a save may write it, and its banner and note. */
export function tagModelSummary(rule) {
  return { tier: rule.tier, savable: tagModelSavable(rule), job: rule.job, banner: rule.banner, note: rule.note, readOnlyColumns: rule.readOnlyColumns };
}
