// tests/tokens-css.test.mjs — content/config/ui/tokens.json (type, layer, motion,
// touch) → tools/tokens-css.mjs → styles/tokens.generated.css.
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, mkdirSync, mkdtempSync, rmSync, copyFileSync, cpSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { buildTokensCss, generateTokensCss, tokenEntries, declaredProperties, TOKENS_JSON, TOKENS_CSS, REM_PX } from '../tools/tokens-css.mjs';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const read = (rel) => readFileSync(join(ROOT, rel), 'utf8').replace(/\r\n/g, '\n');
const tokens = () => JSON.parse(read(TOKENS_JSON));
const BASE = { 'styles/base.css': read('styles/base.css') };

test('the generated stylesheet on disk is exactly the generator output', () => {
  const { css, errors } = buildTokensCss(ROOT);
  assert.deepEqual(errors, []);
  assert.equal(read(TOKENS_CSS), css, 'run node tools/tokens-css.mjs --write');
});

test('every token in tokens.json is published once, in the right unit', () => {
  const { css } = generateTokensCss(tokens(), { stylesheets: BASE });
  assert.match(css, /^\/\* GENERATED by tools\/tokens-css\.mjs from content\/config\/ui\/tokens\.json — do not edit \*\/\n:root \{\n/);
  for (const line of [
    '--t-lead: 1.6rem;', '--t-title-m: 2.2rem;', '--t-title-l: 2.8rem;', '--t-display: 4rem;', '--t-body: 1.4rem;',
    '--layer-base: 0;', '--layer-screen-chrome: 100;', '--layer-blocking: 2000;',
    '--motion-instant: 0ms;', '--motion-fast: 100ms;', '--motion-scene: 400ms;',
    '--touch-comfortable: 48px;', '--touch-primary-row: 56px;', '--touch-min-gap: 8px;',
  ]) assert.ok(css.includes(`  ${line}\n`), line);
  assert.equal(REM_PX, 10, 'html { font-size: 62.5% } makes 1rem 10px');
  assert.match(BASE['styles/base.css'], /html \{[^}]*font-size: 62\.5%/);
});

test('a token that has a home in base.css is not declared again', () => {
  const entries = tokenEntries(tokens());
  const homed = entries.filter((e) => e.home);
  assert.deepEqual(homed.map((e) => e.name).sort(), ['--iconbtn-size', '--t-1', '--t-2', '--t-4', '--tap-floor']);
  const base = declaredProperties(BASE['styles/base.css']);
  const generated = declaredProperties(read(TOKENS_CSS));
  for (const e of homed) {
    assert.ok(base.has(e.name), `${e.name} is declared in base.css`);
    assert.ok(!generated.has(e.name), `${e.name} is not repeated in the generated file`);
  }
  for (const name of generated) assert.ok(!base.has(name), `${name} duplicates a base.css declaration`);
  for (const name of generated) {
    for (const sheet of ['kit.css', 'ui.css', 'combat.css', 'map.css']) {
      assert.ok(!declaredProperties(read(`styles/${sheet}`)).has(name), `${name} is also declared in ${sheet}`);
    }
  }
});

test('a home that does not declare the property, and a duplicate of a stylesheet, are refused by name', () => {
  const t = tokens();
  t.touch.minGapPx.css = '--tap-floor';
  const dup = generateTokensCss(t, { stylesheets: BASE });
  assert.equal(dup.css, null);
  assert.ok(dup.errors.includes(`${TOKENS_JSON}: touch.minGapPx would declare --tap-floor, which styles/base.css already declares — set "home": "styles/base.css" or rename it`), dup.errors.join('\n'));

  const lie = tokens();
  lie.layer = { ...lie.layer };
  lie.touch.comfortablePx = { px: 48, css: '--not-in-base', home: 'styles/base.css' };
  const bad = generateTokensCss(lie, { stylesheets: BASE });
  assert.ok(bad.errors.includes(`${TOKENS_JSON}: touch.comfortablePx.home says styles/base.css declares --not-in-base, but it does not`), bad.errors.join('\n'));

  // A homed property is declared at the root exactly once across the sheets:
  // a later root rule or another stylesheet would override the verified value.
  const kitRoot = { ...BASE, 'styles/kit.css': ':root { --t-1: 2rem; }' };
  const overridden = generateTokensCss(tokens(), { stylesheets: kitRoot });
  assert.ok(overridden.errors.some((e) => e.includes('type.scale.micro.home styles/base.css must hold the only root declaration of --t-1') && e.includes('styles/kit.css')), overridden.errors.join('\n'));
  const twiceHome = { 'styles/base.css': BASE['styles/base.css'] + '\nhtml { --t-1: 2rem; }' };
  assert.ok(generateTokensCss(tokens(), { stylesheets: twiceHome }).errors.some((e) => e.includes('found 2 there')));
  const scopedFirst = { 'styles/base.css': '.component { --t-1: 1rem; }\n' + BASE['styles/base.css'].replace('--t-1: 1rem', '--t-1: 2rem') };
  const wrongRoot = generateTokensCss(tokens(), { stylesheets: scopedFirst });
  assert.ok(wrongRoot.errors.some((e) => e.includes('type.scale.micro.px 10 disagrees with styles/base.css\'s --t-1: 2rem')), 'the root value is checked, not an earlier scoped one: ' + wrongRoot.errors.join('\n'));
  const scoped = { ...BASE, 'styles/kit.css': '.cc-design-workspace { --tap-floor: var(--cc-control-floor); } @media (min-width: 1px) { .x:root-ish { --t-1: 3rem } }' };
  assert.equal(generateTokensCss(tokens(), { stylesheets: scoped }).errors.length, 0, 'a scoped re-declaration is the cascade, not a second home');

  const clash = tokens();
  clash.touch.minGapPx.css = '--layer-hud';
  const twice = generateTokensCss(clash, { stylesheets: BASE });
  assert.ok(twice.errors.includes(`${TOKENS_JSON}: touch.minGapPx and layer.hud both publish --layer-hud`), twice.errors.join('\n'));
});

test('a homed token whose px disagrees with its home is refused; a calc() home asks for px to be dropped', () => {
  const drift = tokens();
  drift.type.scale.micro = { ...drift.type.scale.micro, px: 12 }; // base.css says --t-1: 1rem (10px)
  const r = generateTokensCss(drift, { stylesheets: BASE });
  assert.equal(r.css, null);
  assert.ok(r.errors.some((e) => e.startsWith(`${TOKENS_JSON}: type.scale.micro.px 12 disagrees with styles/base.css's --t-1: 1rem (10px)`)), r.errors.join('\n'));

  const agree = tokens();
  agree.type.scale.micro = { ...agree.type.scale.micro, px: 10 };
  assert.equal(generateTokensCss(agree, { stylesheets: BASE }).errors.length, 0, 'a px that matches the home passes');

  const calc = tokens();
  calc.touch.floorPx = { ...calc.touch.floorPx, px: 44 }; // --tap-floor is a calc() in base.css
  const c = generateTokensCss(calc, { stylesheets: BASE });
  assert.ok(c.errors.some((e) => e.includes('touch.floorPx.px 44 cannot be checked against') && e.includes('drop px here')), c.errors.join('\n'));

  const none = tokens(); // the real file: homed touch entries carry no px at all
  assert.equal(none.touch.floorPx.px, undefined);
  assert.equal(generateTokensCss(none, { stylesheets: BASE }).errors.length, 0);
});

test('a bad token is refused by the config-build rules, naming the file', () => {
  const t = tokens();
  t.layer.hud = 1;
  const { css, errors } = generateTokensCss(t, { stylesheets: BASE });
  assert.equal(css, null);
  assert.ok(errors.some((e) => e.startsWith(`${TOKENS_JSON}: layer.`)), errors.join('\n'));
});

test('--check passes on the real tree and fails on a drifted copy', () => {
  const root = mkdtempSync(join(tmpdir(), 'tokens-css-'));
  try {
    for (const rel of [TOKENS_JSON, TOKENS_CSS, 'styles/base.css']) {
      mkdirSync(dirname(join(root, rel)), { recursive: true });
      copyFileSync(join(ROOT, rel), join(root, rel));
    }
    // The tool resolves ROOT from its own location, so run a copy of it from the temp tree.
    mkdirSync(join(root, 'tools'), { recursive: true });
    for (const name of ['tokens-css.mjs', 'config-build.mjs']) copyFileSync(join(ROOT, 'tools', name), join(root, 'tools', name));
    cpSync(join(ROOT, 'tools', 'lib'), join(root, 'tools', 'lib'), { recursive: true });
    const run = () => execFileSync(process.execPath, ['tools/tokens-css.mjs', '--check'], { cwd: root, encoding: 'utf8', stdio: 'pipe' });
    assert.match(run(), /is current/);
    writeFileSync(join(root, TOKENS_CSS), read(TOKENS_CSS).replace('--layer-hud: 80;', '--layer-hud: 81;'));
    assert.throws(run, (error) => /STALE: styles\/tokens\.generated\.css/.test(String(error.stderr)));
    // Drift the other way: the JSON moves, the stylesheet does not.
    writeFileSync(join(root, TOKENS_CSS), read(TOKENS_CSS));
    const t = tokens();
    t.motion.fast = 120;
    writeFileSync(join(root, TOKENS_JSON), JSON.stringify(t, null, 2));
    assert.throws(run, (error) => /STALE/.test(String(error.stderr)));
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('index.html links the generated sheet straight after base.css', () => {
  const links = [...read('index.html').matchAll(/<link rel="stylesheet" href="([^"]+)"/g)].map((m) => m[1]);
  assert.equal(links[links.indexOf('styles/base.css') + 1], 'styles/tokens.generated.css');
});
