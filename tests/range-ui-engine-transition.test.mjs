import test from 'node:test';
import assert from 'node:assert/strict';
import { contentBundle } from '../src/content/index.js';
import { createRegistries } from '../src/model/registries.js';
import { resolveGameProfile, applyGameProfileToContent, bindGameProfileRegistries } from '../src/model/gameProfile.js';
import { createRunState } from '../src/model/state.js';
import { createRunCombat } from '../src/engine/runCombat.js';
import { createRng } from '../src/engine/rng.js';
import { dispatch, previewCard } from '../src/engine/combat.js';
import { movedEngagementState, rangePairKey } from '../src/model/combatEngagement.js';
import { combatRangeActionPlan, rangeHitLabel } from '../src/ui/models/CombatRangeActionModel.js';

test('selected Throw becomes ordinary price/Precision after authored Advance enters coverage', () => {
  const profile = resolveGameProfile('core');
  const registries = bindGameProfileRegistries(createRegistries(applyGameProfileToContent(contentBundle, profile)), profile);
  const run = createRunState({ registries, seed: 777, classId: 'rogue', profileMeta: { gameProfileUnlocks: { core: { completedRunIds: ['a', 'b', 'c'] } } } });
  const combat = createRunCombat({ registries, run, rng: createRng(777), enemyIds: ['wanderingSoldier'] });
  combat.player.stamina = 4;
  combat.rangeState = movedEngagementState(combat.rangeState, 'player:player', 'enemy:e1', 1);
  const piles = ['hand', 'draw', 'discard', 'exhaust'];
  const strike = piles.flatMap(key => combat.piles[key]).find(card => card.cardId === 'core.strike');
  assert.ok(strike);
  for (const key of piles) combat.piles[key] = combat.piles[key].filter(card => card.instanceId !== strike.instanceId);
  combat.piles.hand.unshift(strike);
  const movement = profile.content.cards.find(card => card.effects?.length && card.effects.every(effect => effect.op === 'moveEngagement') && card.effects[0].bands === -1);
  assert.ok(movement);
  combat.piles.hand.push({ instanceId: 'actual-authored-advance', cardId: movement.id, upgraded: false });
  const far = previewCard(combat, strike.instanceId, 'e1', undefined, { rangeRoute: 'throw' });
  assert.equal(far.range.targets[0].precisionDelta, -1);
  assert.ok(combatRangeActionPlan(far));
  dispatch(combat, { type: 'playCard', cardInstanceId: 'actual-authored-advance', targetId: 'e1' });
  assert.equal(combat.rangeState.engagements[rangePairKey('player:player', 'enemy:e1')], 0);
  const sticky = previewCard(combat, strike.instanceId, 'e1', undefined, { rangeRoute: 'throw' });
  const ordinary = previewCard(combat, strike.instanceId, 'e1', undefined, { rangeRoute: 'advance' });
  assert.equal(sticky.range.targets[0].precisionDelta, 0);
  assert.equal(sticky.cost, ordinary.cost);
  assert.equal(sticky.staminaCost, ordinary.staminaCost);
  assert.equal(sticky.range.targets[0].hitChance, ordinary.range.targets[0].hitChance);
  assert.equal(rangeHitLabel(sticky), rangeHitLabel(ordinary));
  assert.equal(combatRangeActionPlan(sticky), null, 'in-range attack keeps its face clear');
  const before = combat.player.stamina;
  dispatch(combat, { type: 'playCard', cardInstanceId: strike.instanceId, targetId: 'e1', rangeRoute: 'throw' });
  assert.equal(before - combat.player.stamina, ordinary.staminaCost);
  assert.equal(combat.eventLog.filter(event => event.type === 'cardPlayed').at(-1).staminaSpent, ordinary.staminaCost);
});
