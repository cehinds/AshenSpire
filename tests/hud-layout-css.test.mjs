const ROOT = fileURLToPath(new URL('..', import.meta.url));
const read = (rel) => readFileSync(join(ROOT, rel), 'utf8');
const empty = (formFactor) => ({ format: HUD_LAYOUT_FORMAT, formFactor, tokens: {} });
const emptyDocs = () => Object.fromEntries(FORM_FACTORS.map((ff) => [ff, empty(ff)]));
const withTokens = (formFactor, tokens) => ({ ...emptyDocs(), [formFactor]: { ...empty(formFactor), tokens } });

test('the generated stylesheet on disk is exactly the generator output', () => {
  const { css, errors } = buildHudLayoutCss(ROOT);
  assert.deepEqual(errors, []);
  assert.equal(read(HUD_LAYOUT_CSS), css, 'run node tools/hud-layout-css.mjs --write');
});

test('all four form-factor files are present, valid and say their own form factor', () => {
  const { docs, errors } = readHudLayoutDocs(ROOT);
  assert.deepEqual(errors, []);
  assert.deepEqual(Object.keys(docs).sort(), [...FORM_FACTORS].sort());
  for (const ff of FORM_FACTORS) assert.equal(docs[ff].formFactor, ff);
});

test('the output has the contract shape: header, :root defaults, one block per form factor', () => {
  const { css } = generateHudLayoutCss(withTokens('tablet', { '--hud-tools-dy': '-4px' }));
  const lines = css.split('\n');
  assert.match(lines[0], /^\/\* GENERATED by tools\/hud-layout-css\.mjs from content\/hud-layout\/\*\.json — do not edit \*\/$/);
  const root = css.match(/^:root \{\n([\s\S]*?)\n\}$/m)[1];
  assert.deepEqual(root.split('\n').map((line) => line.trim().split(':')[0]), HUD_LAYOUT_TOKENS.map((t) => t.name), 'every token at its default');
  const selectors = [...css.matchAll(/^(:root\[data-form-factor='(\w+)'\])/gm)].map((m) => m[2]);
  assert.deepEqual(selectors, FORM_FACTORS);
  assert.match(css, /:root\[data-form-factor='tablet'\] \{\n {2}--hud-tools-dy: -4px;\n\}/);
  assert.match(css, /:root\[data-form-factor='mobile'\] \{ \}/, 'an empty file overrides nothing');
});

test('an empty set of files generates only the defaults', () => {
  const { css, errors } = generateHudLayoutCss(emptyDocs());
  assert.deepEqual(errors, []);
  assert.equal((css.match(/--hud-/g) || []).length, HUD_LAYOUT_TOKENS.length);
});

test('an unknown token is refused by file and name', () => {
  const { css, errors } = generateHudLayoutCss(withTokens('mobile', { '--hud-banana': '1px' }));
  assert.equal(css, null);
  assert.deepEqual(errors, ["content/hud-layout/mobile.json: unknown token '--hud-banana'"]);
});

test('a wrong formFactor, a missing file and a wrong format are refused', () => {
  const docs = emptyDocs();
  docs.desktop = { ...empty('tablet') };
  delete docs.widescreen;
  docs.mobile = { ...empty('mobile'), format: 'something/2' };
  const { css, errors } = generateHudLayoutCss(docs);
  assert.equal(css, null);
  assert.ok(errors.some((e) => e.startsWith('content/hud-layout/desktop.json:') && /does not match the file name/.test(e)), errors.join('\n'));
  assert.ok(errors.some((e) => e.startsWith('content/hud-layout/widescreen.json: missing')), errors.join('\n'));
  assert.ok(errors.some((e) => e.startsWith('content/hud-layout/mobile.json: format')), errors.join('\n'));
});

