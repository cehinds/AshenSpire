test('geometry offsets: zero is the placement, a clamp keeps bounds, a new overlap is refused', () => {
  const rect = { left: 100, top: 100, width: 50, height: 20 };
  assert.deepEqual(offsetPlacement({ rect }), { left: 100, top: 100, shifted: false });
  const bounds = { left: 0, right: 200, top: 0, bottom: 150 };
  assert.deepEqual(offsetPlacement({ rect, dx: 500, dy: 500, bounds }), { left: 150, top: 130, shifted: true });
  const control = { left: 100, right: 150, top: 125, bottom: 135 };
  assert.deepEqual(offsetPlacement({ rect, dy: 20, bounds, obstacles: [control] }), { left: 100, top: 100, shifted: false });
  const own = { left: 90, right: 110, top: 95, bottom: 105 };
  assert.deepEqual(offsetPlacement({ rect, dx: 5, bounds, obstacles: [own] }), { left: 105, top: 100, shifted: true });
  const style = { getPropertyValue: (name) => ({ '--hud-tools-dy': ' -6px', '--hud-player-details-dx': '' }[name] ?? '0px') };
  assert.deepEqual(hudGeometry(style), { playerDetailsDx: 0, playerDetailsDy: 0, enemyNameplateDy: 0, turnRibbonDy: 0, toolsDy: -6 });
});

