  const rect = { left: 100, top: 100, width: 50, height: 20 };
  assert.deepEqual(offsetPlacement({ rect }), { left: 100, top: 100, shifted: false });
  const bounds = { left: 0, right: 200, top: 0, bottom: 150 };
