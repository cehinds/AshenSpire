// tests/hud-layout-css.test.mjs — the HUD layout token pipeline
// (docs/hud-layout-tokens.md): content/hud-layout/*.json → tools/hud-layout-css.mjs
// → styles/hud-layout.generated.css, its consumers, and the form-factor decider.
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { FORM_FACTORS, HUD_LAYOUT_FORMAT, HUD_LAYOUT_TOKENS, PER_CONSUMER, hudLayoutToken, checkTokenValue } from '../tools/hud-layout-tokens.mjs';
import { buildHudLayoutCss, generateHudLayoutCss, readHudLayoutDocs, HUD_LAYOUT_CSS } from '../tools/hud-layout-css.mjs';
import { formFactorFor } from '../src/ui/models/FormFactorModel.js';
import { offsetPlacement, hudGeometry } from '../src/ui/models/HudLayoutOffsetModel.js';
import { balance } from '../src/content/balance.js';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const read = (rel) => readFileSync(join(ROOT, rel), 'utf8');
const empty = (formFactor) => ({ format: HUD_LAYOUT_FORMAT, formFactor, tokens: {} });
const emptyDocs = () => Object.fromEntries(FORM_FACTORS.map((ff) => [ff, empty(ff)]));
const withTokens = (formFactor, tokens) => ({ ...emptyDocs(), [formFactor]: { ...empty(formFactor), tokens } });

test('the generated stylesheet on disk is exactly the generator output', () => {
  const { css, errors } = buildHudLayoutCss(ROOT);
  assert.deepEqual(errors, []);
  assert.equal(read(HUD_LAYOUT_CSS), css, 'run node tools/hud-layout-css.mjs --write');
});

test('all four form-factor files are present, valid and say their own form factor', () => {
  const { docs, errors } = readHudLayoutDocs(ROOT);
  assert.deepEqual(errors, []);
  assert.deepEqual(Object.keys(docs).sort(), [...FORM_FACTORS].sort());
  for (const ff of FORM_FACTORS) assert.equal(docs[ff].formFactor, ff);
});

test('the output has the contract shape: header, :root defaults, one block per form factor', () => {
  const { css } = generateHudLayoutCss(withTokens('tablet', { '--hud-tools-dy': '-4px' }));
  const lines = css.split('\n');
  assert.match(lines[0], /^\/\* GENERATED by tools\/hud-layout-css\.mjs from content\/hud-layout\/\*\.json — do not edit \*\/$/);
  const root = css.match(/^:root \{\n([\s\S]*?)\n\}$/m)[1];
  assert.deepEqual(root.split('\n').map((line) => line.trim().split(':')[0]), HUD_LAYOUT_TOKENS.map((t) => t.name), 'every token at its default');
  const selectors = [...css.matchAll(/^(:root\[data-form-factor='(\w+)'\])/gm)].map((m) => m[2]);
  assert.deepEqual(selectors, FORM_FACTORS);
  assert.match(css, /:root\[data-form-factor='tablet'\] \{\n {2}--hud-tools-dy: -4px;\n\}/);
  assert.match(css, /:root\[data-form-factor='mobile'\] \{ \}/, 'an empty file overrides nothing');
});

test('an empty set of files generates only the defaults', () => {
  const { css, errors } = generateHudLayoutCss(emptyDocs());
  assert.deepEqual(errors, []);
  assert.equal((css.match(/--hud-/g) || []).length, HUD_LAYOUT_TOKENS.length);
});

test('an unknown token is refused by file and name', () => {
  const { css, errors } = generateHudLayoutCss(withTokens('mobile', { '--hud-banana': '1px' }));
  assert.equal(css, null);
  assert.deepEqual(errors, ["content/hud-layout/mobile.json: unknown token '--hud-banana'"]);
});

test('a wrong formFactor, a missing file and a wrong format are refused', () => {
  const docs = emptyDocs();
  docs.desktop = { ...empty('tablet') };
  delete docs.widescreen;
  docs.mobile = { ...empty('mobile'), format: 'something/2' };
  const { css, errors } = generateHudLayoutCss(docs);
  assert.equal(css, null);
  assert.ok(errors.some((e) => e.startsWith('content/hud-layout/desktop.json:') && /does not match the file name/.test(e)), errors.join('\n'));
  assert.ok(errors.some((e) => e.startsWith('content/hud-layout/widescreen.json: missing')), errors.join('\n'));
  assert.ok(errors.some((e) => e.startsWith('content/hud-layout/mobile.json: format')), errors.join('\n'));
});

test('bad values fail their type check', () => {
  const bad = {
    '--hud-text-shadow': ['red', '1px', '0 1px 2px #000;', '0 0 1px url(x)', 'inset inset 1px 1px'],
    '--hud-panel-bg': ['12px', 'none', '#12', 'rgb(0,0,0); x', 'initial'],
    '--hud-text-plate-radius': ['3', 'none', 'calc(3px)', '3vw'],
    '--hud-header-hp-max-width': ['wide', 'auto'],
    '--hud-tools-span': ['cards', 'Hand'],
    '--hud-player-details-dx': ['3', '3em', '3px !important'],
    '--hud-details-font': ['Georgia; color: red', '12px', 'a, , b'],
  };
  for (const [name, values] of Object.entries(bad)) {
    for (const value of values) {
      assert.ok(checkTokenValue(hudLayoutToken(name), value), `${name}: '${value}' should be refused`);
      const { errors } = generateHudLayoutCss(withTokens('desktop', { [name]: value }));
      assert.equal(errors.length, 1);
      assert.ok(errors[0].startsWith(`content/hud-layout/desktop.json: ${name}:`), errors[0]);
    }
  }
  const good = {
    '--hud-text-shadow': ['none', '0 1px 2px #000, 0 0 4px #000c', 'inset 0 1px 0 #ffffff36', '1px 1px rgba(0, 0, 0, .5)'],
    '--hud-panel-bg': ['#1c1812f2', 'transparent', 'rgb(0 0 0 / 50%)'],
    '--hud-text-plate-radius': ['3px', '0', '50%', '.2rem'],
    '--hud-header-hp-max-width': ['48%', 'none', '20rem'],
    '--hud-tools-span': ['field', 'hand'],
    '--hud-player-details-dx': ['0px', '-12px', '3.5px'],
    '--hud-details-font': ["'Cinzel', Georgia, 'Times New Roman', serif", 'serif'],
  };
  for (const [name, values] of Object.entries(good)) {
    for (const value of values) assert.equal(checkTokenValue(hudLayoutToken(name), value), null, `${name}: '${value}'`);
  }
});

// THE DEFAULTS TABLE EQUALS THE LITERALS. A token with one pre-pipeline
// literal defaults to it, and its consumer reads var(--token). A token whose
// consumers disagreed defaults to PER_CONSUMER (`initial`), and each consumer
// carries its old literal as the fallback: var(--token, <literal>). Either way
// an empty set of files changes nothing.
test('every default reproduces the pre-pipeline literal at its consumer', () => {
  const PRE_PIPELINE = {
    '--hud-text-plate-bg': 'transparent', // no plate existed
    '--hud-text-plate-radius': '0px',
    '--hud-text-plate-pad': '0px',
    '--hud-tools-bg': 'transparent', // the row's old `background: none`
    '--hud-header-hp-max-width': 'none',
    '--hud-tools-span': 'field',
    '--hud-player-details-dx': '0px', '--hud-player-details-dy': '0px', '--hud-enemy-nameplate-dy': '0px',
    '--hud-turn-ribbon-dy': '0px', '--hud-tools-dy': '0px',
  };
  for (const token of HUD_LAYOUT_TOKENS) {
    assert.ok(token.consumers.length > 0, `${token.name} has a consumer`);
    if (token.default === PER_CONSUMER) {
      for (const { file, fallback } of token.consumers) {
        assert.ok(fallback, `${token.name}: a per-consumer default names each consumer's literal`);
        assert.ok(read(file).includes(`var(${token.name}, ${fallback})`), `${file} reads var(${token.name}, ${fallback})`);
      }
    } else {
      assert.equal(token.default, PRE_PIPELINE[token.name], `${token.name} default`);
      assert.equal(checkTokenValue(token, token.default), null, `${token.name} default passes its own type`);
      for (const { file } of token.consumers) assert.ok(read(file).includes(token.name), `${file} consumes ${token.name}`);
    }
  }
});

