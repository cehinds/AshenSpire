import assert from 'node:assert/strict';
import { stanceOf, stanceEntryBonuses, stanceRatingBonus, stanceStaminaCost } from '../src/model/stanceRules.js';
import { enemyMoveSpOf } from '../src/model/actionCosts.js';
import { primeEnemyCounter } from '../src/engine/combatCardTactics.js';
import { setCombatStance, startTacticalTurn } from '../src/engine/combatMatchups.js';
const ctx = { combatExpansionVersion: 2, queue: [], emit() {}, enqueue(action) { this.queue.push(action); } };
const card = (maneuver, camp = 'physical', school = undefined, range = 'melee') => ({ combatProfile: { maneuver, camp, school, range } });
const entity = { id: 'test', alive: true };
assert.deepEqual(stanceEntryBonuses(card('counter')), { precision: 1, evade: 0, block: 3, barrier: 0 });
assert.deepEqual(stanceEntryBonuses(card('defend', 'spell', 'frost')), { precision: 0, evade: 0, block: 2, barrier: 1 });
assert.deepEqual(stanceEntryBonuses(card('defend', 'spell', 'force')), { precision: 0, evade: 0, block: 2, barrier: 1 });
assert.deepEqual(stanceEntryBonuses(card('defend', 'spell', 'fire')), { precision: 0, evade: 0, block: 1, barrier: 2 });
assert.equal(stanceOf(card('attack', 'spell', 'fire', 'ranged')).maneuver, 'casting');
setCombatStance(ctx, entity, card('attack'));
assert.equal(ctx.queue.length, 1);
setCombatStance(ctx, entity, card('attack'));
assert.equal(ctx.queue.length, 1, 'same stance does not refresh Precision');
setCombatStance(ctx, entity, card('attack', 'physical', undefined, 'ranged'));
assert.equal(entity.combatStance.range, 'ranged', 'same stance refreshes card metadata');
assert.equal(ctx.queue.length, 1, 'metadata refresh grants no entry bonus');
assert.equal(stanceRatingBonus(ctx, entity, 'ar'), 1);
assert.equal(stanceStaminaCost(2, entity, card('attack'), ctx), 1);
assert.equal(stanceStaminaCost(1, entity, card('attack'), ctx), 1);
assert.equal(stanceStaminaCost(2, entity, card('smash'), ctx), 2);
setCombatStance(ctx, entity, card('defend'));
assert.equal(stanceRatingBonus(ctx, entity, 'ar'), 0, 'old bonus disappears');
assert.equal(stanceRatingBonus(ctx, entity, 'dr'), 3);
const before = ctx.queue.length;
setCombatStance(ctx, entity, card('defend'));
assert.equal(ctx.queue.length - before, 2, 'defense repeat restores both pools with overflow');
assert.deepEqual(startTacticalTurn(ctx, entity), { block: 0, barrier: 0 }, 'no legacy repeated turn grant');
setCombatStance(ctx, entity, card('casting', 'spell', 'fire', 'ranged'));
assert.equal(stanceStaminaCost(1, entity, card('casting', 'spell', 'fire', 'ranged'), ctx), 0);
assert.equal(stanceRatingBonus({ combatExpansionVersion: 1 }, entity, 'pr'), 0);
const meleeSpell = { combatStance: stanceOf(card('attack', 'spell', 'fire', 'melee')) };
assert.equal(stanceRatingBonus(ctx, meleeSpell, 'ar'), 1);
assert.equal(stanceRatingBonus(ctx, meleeSpell, 'pr'), 0);
const spellCounter = { combatStance: stanceOf(card('counter', 'spell', 'force', 'melee')) };
assert.equal(stanceRatingBonus(ctx, spellCounter, 'pr'), 1);
assert.equal(enemyMoveSpOf({ sp: 2, combatProfile: { camp: 'spell', maneuver: 'casting', range: 'ranged' } }, 'cast', 1, { entity, ctx }), 1);
const enemy = { id: 'enemy', enemyId: 'fixture', kind: 'enemy', alive: true, statuses: {},
  persistentPoise: { value: 0, max: 20 }, persistentWard: { value: 0, max: 20 } };
primeEnemyCounter(ctx, enemy, { tags: ['camp:physical', 'maneuver:defend'], effects: [] }, 'guard');
assert.equal(enemy.persistentPoise.value, 5, 'one telegraph restores once');
assert.equal(enemy.persistentWard.value, 5);
primeEnemyCounter(ctx, enemy, { tags: ['camp:physical', 'maneuver:defend'], effects: [] }, 'guard');
assert.equal(enemy.persistentPoise.value, 10, 'later Defense play restores again');
console.log('stance lifecycle assertions passed');
