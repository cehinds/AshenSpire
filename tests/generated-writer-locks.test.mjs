import test from 'node:test';
import assert from 'node:assert/strict';
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, utimesSync, writeFileSync } from 'node:fs';
import { spawn, spawnSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { tryAcquire, lockEnv, lockPath, TOKEN_ENV } from '../tools/lib/build-lock.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const fixture = mkdtempSync(join(tmpdir(), 'ashen-generated-writers-'));
process.on('exit', () => rmSync(fixture, { recursive: true, force: true }));
// Exercise the production CLIs and their import-only ROOT discovery entirely
// outside the repository. No test probe may collide with a shared importer.
for (const name of ['src', 'engine', 'games/ashenspire', 'content/source', 'tools/base-cards.mjs', 'tools/game-config.mjs', 'tools/catalog-json.mjs', 'tools/lib']) {
  const out = join(fixture, name); mkdirSync(dirname(out), { recursive: true });
  cpSync(join(root, name), out, { recursive: true });
}
const base = 'src/content/generated/baseCards.js';
const writers = [
  { script: 'tools/base-cards.mjs', args: [], outputs: [base] },
  { script: 'tools/game-config.mjs', args: ['build'], outputs: [base, 'src/content/generated/gameProfiles.js', 'games/ashenspire/game.lock.json'] },
];
const env = () => { const value = { ...process.env }; delete value[TOKEN_ENV]; return value; };
const run = (writer, extra = {}) => spawnSync(process.execPath, [writer.script, ...writer.args], {
  cwd: fixture, encoding: 'utf8', timeout: 20000, env: { ...env(), ...extra },
});
const success = result => assert.equal(result.status, 0, `${result.error || ''}\n${result.stdout}${result.stderr}`);

for (const writer of writers) {
  test(`${writer.script} waits for the shared writer lock before touching stale generated bytes`, { timeout: 30000 }, async () => {
    const target = join(fixture, base), original = readFileSync(target, 'utf8');
    const stale = original + '\n// isolated stale-generation probe\n'; writeFileSync(target, stale);
    const release = tryAcquire(fixture, 'test parent writer'); assert.equal(typeof release, 'function');
    let waited = false, bytesWhileLocked;
    try {
      const child = spawn(process.execPath, [writer.script, ...writer.args], { cwd: fixture, env: env(), stdio: ['ignore', 'pipe', 'pipe'] });
      let stdout = '', stderr = '';
      child.stdout.on('data', chunk => { stdout += chunk; });
      child.stderr.on('data', chunk => {
        stderr += chunk;
        if (!waited && /waiting for test parent writer/.test(stderr)) {
          waited = true;
          bytesWhileLocked = readFileSync(target, 'utf8');
          release();
        }
      });
      const code = await new Promise((resolve, reject) => { child.once('error', reject); child.once('close', resolve); });
      assert.equal(code, 0, stdout + stderr); assert.ok(waited, 'the CLI participated in the shared lock protocol');
      assert.equal(bytesWhileLocked, stale, 'no generated byte changes while the other writer owns the lock');
      assert.equal(readFileSync(target, 'utf8'), original, 'the pending compile proceeds after release');
      assert.equal(existsSync(lockPath(fixture)), false, 'the child releases its own lock');
    } finally { release(); }
  });

  test(`${writer.script} inherits a live builder token and leaves unchanged outputs untouched`, () => {
    const release = tryAcquire(fixture, 'export parent'); assert.equal(typeof release, 'function');
    try {
      // The first game-config compile can refresh its fixture-specific runtime
      // pin. Once current, a second build must not truncate or rename outputs.
      success(run(writer, lockEnv(release)));
      const stamp = new Date('2001-01-01T00:00:00Z');
      for (const file of writer.outputs) utimesSync(join(fixture, file), stamp, stamp);
      const before = writer.outputs.map(file => { const info = statSync(join(fixture, file)); return { file, ino: info.ino, mtimeMs: info.mtimeMs, bytes: readFileSync(join(fixture, file), 'utf8') }; });
      const result = run(writer, lockEnv(release)); success(result);
      assert.doesNotMatch(result.stderr, /waiting for/);
      assert.equal(JSON.parse(readFileSync(lockPath(fixture), 'utf8')).token, release.token, 'a nested builder does not replace or release its parent lock');
      for (const prior of before) {
        const info = statSync(join(fixture, prior.file));
        assert.equal(info.mtimeMs, prior.mtimeMs, `${prior.file}: no needless rewrite`);
        assert.equal(info.ino, prior.ino, `${prior.file}: no needless atomic replacement`);
        assert.equal(readFileSync(join(fixture, prior.file), 'utf8'), prior.bytes);
      }
    } finally { release(); }
  });
}
