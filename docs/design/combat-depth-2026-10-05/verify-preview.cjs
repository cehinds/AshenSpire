const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'D:/repos/TheAshenedSpire/node_modules/playwright');
const root=__dirname;
const out=path.join(root,'review');fs.mkdirSync(out,{recursive:true});
const url=process.env.PREVIEW_URL || 'http://127.0.0.1:4189/docs/design/combat-depth-2026-10-05/';
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1600,height:1050},deviceScaleFactor:1});
 const issues=[];page.on('pageerror',e=>issues.push(String(e)));page.on('response',r=>{if(r.status()>=400)issues.push(`${r.status()} ${r.url()}`)});
 await page.goto(url,{waitUntil:'networkidle'});
 await page.locator('#hero-sprite img').waitFor();
 await page.screenshot({path:path.join(out,'desktop.png'),fullPage:true});
 await page.locator('#stage').screenshot({path:path.join(out,'battlefield.png')});
 await page.locator('[data-toggle="ruins"]').uncheck();
 if(!await page.locator('[data-layer="ruins"]').evaluate(e=>getComputedStyle(e).visibility==='hidden'))throw Error('Layer toggle failed');
 await page.locator('[data-toggle="ruins"]').check();
 const stage=await page.locator('#stage').boundingBox();await page.mouse.move(stage.x+stage.width*.9,stage.y+stage.height*.2);
 await page.waitForTimeout(100);
 const moved=await page.locator('[data-layer="far"]').evaluate(e=>getComputedStyle(e).transform);
 if(moved==='none')throw Error('Depth motion did not move');
 await page.locator('#hero').selectOption('starseer-default');
 if(!await page.locator('#hero-sprite img').getAttribute('src').then(s=>s.includes('starseer-default')))throw Error('Hero selection failed');
 await page.locator('[data-tab="catalog"]').click();await page.locator('#family').selectOption('armor');
 await page.locator('#backdrop').selectOption('light');
 await page.locator('#grid img').evaluateAll(images=>Promise.all(images.map(i=>{i.loading='eager';return i.decode()})));
 await page.screenshot({path:path.join(out,'armor-light.png'),fullPage:true});
 await page.locator('#search').fill('nightweave');
 if(await page.locator('.tile').count()!==1)throw Error('Search failed');
 await page.locator('.tile').click();if(!await page.locator('#detail').isVisible())throw Error('Details failed');await page.locator('#close').click();
 await page.locator('#search').fill('');await page.locator('#family').selectOption('enemy');await page.locator('#backdrop').selectOption('checker');
 await page.locator('#grid img').evaluateAll(images=>Promise.all(images.map(i=>{i.loading='eager';return i.decode()})));
 await page.screenshot({path:path.join(out,'enemies-checker.png'),fullPage:true});
 await page.locator('[data-tab="scene"]').click();await page.locator('#reset').click();await page.locator('#hero').selectOption('reaver-default');
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:path.join(out,'phone.png'),fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);if(overflow)throw Error('Horizontal overflow on phone');
 await page.emulateMedia({reducedMotion:'reduce'});await page.waitForTimeout(80);
 if(await page.locator('[data-layer="far"]').evaluate(e=>getComputedStyle(e).transform)!=='none')throw Error('Reduced motion failed');
 const broken=await page.locator('img').evaluateAll(images=>images.filter(i=>!i.complete||!i.naturalWidth).map(i=>i.src));
 const report={url,spriteCount:JSON.parse(fs.readFileSync(path.join(root,'catalog.json'),'utf8')).coverage.generated,issues,broken,checks:['desktop scene screenshot','independent layer toggles','pointer parallax','hero selection','armor catalog on light','search and detail dialog','enemy alpha checker','390px layout','reduced motion'],timestamp:new Date().toISOString()};
 fs.writeFileSync(path.join(out,'browser-report.json'),JSON.stringify(report,null,2));await browser.close();
 console.log(JSON.stringify(report,null,2));if(issues.length||broken.length)process.exitCode=1;
})().catch(e=>{console.error(e);process.exitCode=1});
